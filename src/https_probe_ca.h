// EST-388 + EST-389: the trust anchors the `https probe` validates the game server against.
//
// TWO roots, ONE buffer. What game.cl0.eu actually serves (checked from TestBox 2026-11-11 11:43,
// `openssl s_client -connect game.cl0.eu:443 -servername game.cl0.eu -showcerts`, verify 0):
//   leaf CN=game.cl0.eu -> CN=YE1 (Let's Encrypt) -> CN=Root YE -> issued by ISRG Root X2
// EST-388 pinned ISRG Root X1 only (the older RSA chain), so every probe would have failed the
// certificate check and the failure would have read like a memory problem. Both roots are pinned
// here: X1 for the old chain, X2 for the chain the server sends today.
//
// Why one buffer instead of two: mbedTLS parses a buffer holding several concatenated PEM
// certificates into one CA chain (mbedtls_x509_crt_parse, "one or more concatenated PEM-encoded
// certificates", vendored header checked), and WiFiClientSecure passes that buffer through with
// MBEDTLS_SSL_VERIFY_REQUIRED, so validation stays ON and the chain may end at either root.
//
// SHA-256 of each DER, in buffer order:
//   ISRG Root X1 (RSA, the older chain):
//     96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:CF:E8:A3:C0:AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6
//   ISRG Root X2 (ECDSA P-384, the chain served today):
//     69:72:9B:8E:15:A8:6E:FC:17:7A:57:AF:B7:17:1D:FC:64:AD:D2:8C:2F:CA:8C:F1:50:7E:34:45:3C:CB:14:70
// test_est389.py decodes every PEM in this file and fails the run when a certificate stops
// matching its fingerprint above or the published value.
//
// The two blocks are adjacent raw string literals, so the compiler joins them into ONE NUL-terminated
// buffer: nothing is duplicated in flash and the parse call takes the whole list. Public root
// certificates are public data, not a secret.
