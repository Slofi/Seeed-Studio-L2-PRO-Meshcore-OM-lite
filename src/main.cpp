constexpr int kChatMaxLines = 16;   // a 96-byte message needs at most ~4, but never truncate text
constexpr int kChatCols = 64;

static int wrapLines(lgfx::LovyanGFX* d, const char* text, char lines[kChatMaxLines][kChatCols],
                     int maxPx) {
  int n = 0;
  lines[0][0] = 0;
  for (const char* p = text; *p && n < kChatMaxLines; ) {
    if (*p == ' ') { ++p; continue; }
    const char* w = p;
    int wl = 0;
    while (w[wl] && w[wl] != ' ') ++wl;
    const bool hasText = lines[n][0] != 0;
    char trial[kChatCols];
    snprintf(trial, sizeof(trial), "%s%s%.*s", lines[n], hasText ? " " : "", wl, w);
    if (hasText && d->textWidth(trial) > maxPx) {
      if (++n >= kChatMaxLines) break;
      snprintf(lines[n], sizeof(lines[0]), "%.*s", wl, w);
    } else {
      snprintf(lines[n], sizeof(lines[0]), "%s", trial);
    }
    p = w + wl;
  }
  const int used = (lines[n][0] != 0) ? n + 1 : n;
  return used > 0 ? used : 1;
}

// Relative age from the stored uptime stamp. There is no RTC on this board, so "12m" means twelve
// minutes of this power cycle, and the heartbeat/uptime is the only honest clock we have.
static void fmtAge(char* out, size_t n, uint32_t ts) {
  const uint32_t now = millis() / 1000;
  const uint32_t age = (now >= ts) ? (now - ts) : 0;
  if (age < 60) snprintf(out, n, "%us", (unsigned)age);
  else if (age < 3600) snprintf(out, n, "%um", (unsigned)(age / 60));
  else snprintf(out, n, "%uh", (unsigned)(age / 3600));
}

