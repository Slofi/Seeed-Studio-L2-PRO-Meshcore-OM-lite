// EST-350: the ONE way to move to another page. Leaving a page records where it was scrolled to, so
// Back (settingsBack) returns there; Back itself is the other end of the same record.
static void setGo(SetPage p) {
  if (p != g_setPage) g_setNav.push(g_setPage, g_setScroll);
  g_setPage = p;
  g_setScroll = 0;
  g_setSelOpen = false;
  g_deleteArmed = false;
  // EST-352: every door into a text editor opens the shared sheet on the letters page with shift
  // off, exactly the chat sheet's rule; the accented-letter hold starts clean. EST-354: the Wi-Fi
  // password also starts hidden and empty.
  if (p == SetPage::NameEdit || p == SetPage::ChanKey || p == SetPage::WifiPass) {
    g_setEditNums = false;
    g_setEditShift = false;
    g_setEditReveal = false;
    if (p == SetPage::WifiPass) g_editBuf[0] = 0;
    g_setAccentRow = -1;
    g_setAccentCol = -1;
    g_setAccentCp = 0;
    g_setAccentPreview = false;
  }
}

// Back from an action (Join, Apply, Use, Delete) to the page it was opened from: the same step, run
// backwards, so that page comes back at the scroll it had.
static void setBack() {
  SetPage p = g_setPage;
  int scroll = 0;
  if (!g_setNav.pop(&p, &scroll)) {
    g_setPage = SetPage::GeneralRoot;
    g_setScroll = 0;
  } else {
    g_setPage = p;
    g_setScroll = scroll;
  }
  g_setSelOpen = false;
  g_deleteArmed = false;
}

