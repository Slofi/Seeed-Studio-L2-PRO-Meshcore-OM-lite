// The emoji Recent row: 16 little-endian u32 then the valid count, 65 bytes in NVS "omlite".
// Unknown trailing bytes are ignored by restore(), so an older/longer blob is safe.
static void saveEmojiRecent() {
  uint8_t buf[4 * om::ui::kEmojiRecentMax + 1];
  for (int i = 0; i < om::ui::kEmojiRecentMax; ++i) {
    const uint32_t cp = g_emojiRecent.cps[i];
    buf[i * 4 + 0] = (uint8_t)(cp & 0xFF);
    buf[i * 4 + 1] = (uint8_t)((cp >> 8) & 0xFF);
    buf[i * 4 + 2] = (uint8_t)((cp >> 16) & 0xFF);
    buf[i * 4 + 3] = (uint8_t)((cp >> 24) & 0xFF);
  }
  buf[4 * om::ui::kEmojiRecentMax] = g_emojiRecent.count;
  g_prefs.putBytes("erec", buf, sizeof(buf));
}

static void loadEmojiRecent() {
  uint8_t buf[4 * om::ui::kEmojiRecentMax + 1];
  const size_t n = g_prefs.getBytesLength("erec");
  if (n != sizeof(buf)) return;
  if (g_prefs.getBytes("erec", buf, sizeof(buf)) != sizeof(buf)) return;
  uint32_t raw[om::ui::kEmojiRecentMax];
  for (int i = 0; i < om::ui::kEmojiRecentMax; ++i) {
    raw[i] = (uint32_t)buf[i * 4] | ((uint32_t)buf[i * 4 + 1] << 8) |
             ((uint32_t)buf[i * 4 + 2] << 16) | ((uint32_t)buf[i * 4 + 3] << 24);
  }
  g_emojiRecent.restore(raw, om::ui::kEmojiRecentMax, buf[4 * om::ui::kEmojiRecentMax]);
}

// The floor is persisted every 10 minutes and on every applied sync (the caller calls this then). It
// is a lower bound only: the next boot starts at max(floor, build time) and still reports "--:--"
// until a real source sets the clock.
static void saveTimeFloor() {
  const uint32_t floor = om::timeKeeper().floor();
  const bool ok = g_prefs.putUInt("tfloor", floor) == sizeof(uint32_t);
  // Rate-limit even a failed write: retrying every loop would hammer NVS. A failed save is retried
  // with the normal 10-minute cadence, and the floor is still raised in RAM.
  om::timeKeeper().onFloorSaved(millis() / 1000);
  if (!ok) Serial.printf("[time] floor %lu not saved to NVS\n", (unsigned long)floor);
}

