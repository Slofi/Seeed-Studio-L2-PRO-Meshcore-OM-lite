// --- the editor's shared sheet (EST-352) --------------------------------------------------------
// One place that knows which field is open and which buffer it edits. The character filter and the
// byte limit come from ui/chat_layout.h, the same rules the host test checks.
static om::ui::KeyboardField settingsEditField() {
  return om::ui::settingsEditorField(g_setEditor);
}

static char* settingsEditBuf() { return g_setPage == SetPage::ChanKey ? g_keyText : g_editBuf; }

static bool settingsEditAppendBytes(const char* bytes, int n) {
  if (bytes == nullptr || n <= 0) return false;
  char* buf = settingsEditBuf();
  const size_t cap = g_setPage == SetPage::ChanKey ? sizeof(g_keyText) : sizeof(g_editBuf);
  const int used = (int)strlen(buf);
  if (!om::ui::keyboardAcceptsBytes(settingsEditField(), used, n)) return false;
  if ((size_t)used + (size_t)n >= cap) return false;
  memcpy(buf + used, bytes, (size_t)n);
  buf[used + n] = 0;
  return true;
}

static bool settingsEditAppendChar(char ch) {
  if (!om::ui::keyboardAllowsChar(settingsEditField(), ch)) return false;
  return settingsEditAppendBytes(&ch, 1);
}

// The release of a held s/c/z: two UTF-8 bytes through the same byte budget as any other key.
static bool settingsEditAppendAccent() {
  if (g_setAccentCp == 0) return false;
  char bytes[4] = {0};
  const int n = om::ui::utf8Encode(g_setAccentCp, bytes);
  if (n <= 0) return false;
  return settingsEditAppendBytes(bytes, n);
}

static void redrawMainTab() {
  if (g_tab == 0) drawHome();
  else if (g_tab == 1) drawChat();
  else if (g_tab == 2) drawMapTab();
  else drawRptrTab();
}

static void drawSettings() {
  buildSettingsRows();
  const om::ui::SettingsLayout L =
      om::ui::settingsLayoutFor(om::ui::kScreenW, om::ui::kScreenH, g_setSubPage, g_setSelOpen);
  g_setMaxScroll = om::ui::settingsMaxScroll(L, g_setRows, g_setRowCount);
  // The dropdown's clamp is the Chat tab's own: same list, same content height (the shared clamp).
  om::ui::SelectorModel sel;
  sel.chatCount = g_chatCount;
  sel.channelCount = g_channelCount;
  sel.dmCount = g_chatCount - g_channelCount;
  g_setSelMaxScroll = g_setSelOpen ? om::ui::selectorMaxScroll(sel, L.selList) : 0;
  if (g_setSelScroll > g_setSelMaxScroll) g_setSelScroll = g_setSelMaxScroll;
  if (g_setSelScroll < 0) g_setSelScroll = 0;
  const om::ui::SettingsView v = settingsView();
  om::ui::settingsScreenDraw(v);
}

static void openSettings(int mainTab, om::ui::SettingsTab tab) {
  (void)mainTab;
  g_settings = true;
  g_setTab = tab;
  g_setPage = setRootForTab(tab);
  g_setScroll = 0;
  g_setNav.reset();                 // a fresh door into Settings has no history behind it
  g_setEditor = om::ui::SettingsEditor::None;
  g_deleteArmed = false;
  g_setSelOpen = false;
  g_setSelScroll = 0;
  // EST-350: the settings page starts on the chat that was open when the gear was pressed.
  g_setChat = g_chatSel;
  if (tab == om::ui::SettingsTab::Chat) refreshChats();
  buildSettingsRows();
  drawSettings();
}

static void settingsBack() {
  // EST-354: Back out of the password sheet wipes the typed secret; it is not needed after leaving.
  if (g_setPage == SetPage::WifiPass) {
    memset(g_editBuf, 0, sizeof(g_editBuf));
    g_setEditText[0] = 0;
    g_setEditReveal = false;
  }
  // EST-350: Back is one step of the history setGo() builds, so it needs no table per page: the page
  // it returns to is the one the user came from, at the scroll it was left at. An empty history means
  // this is a root page: Back leaves Settings for the screen the gear was pressed on.
  if (g_setNav.empty()) {
    g_settings = false;
    g_setEditor = om::ui::SettingsEditor::None;
    g_deleteArmed = false;
    g_setSelOpen = false;
    redrawMainTab();
    return;
  }
  setBack();
  g_setEditor = om::ui::SettingsEditor::None;
  drawSettings();
}

static void openChannelPage(int idx) {
  if (idx < 0 || idx >= om::mcChannelCount()) return;
  g_chanPage = idx;
  setGo(SetPage::Channel);
  drawSettings();
}

