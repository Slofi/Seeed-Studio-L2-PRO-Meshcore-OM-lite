// One row's action. The id is the only thing the shell needs to know about a row.
static void handleSettingsRow(uint16_t id) {
  if (g_setTab == om::ui::SettingsTab::Chat) refreshChats();
  const int ch = settingsChatChannel();
  switch (id) {
    case A_Preset:   setGo(SetPage::Preset); break;
    case A_Hash:     setGo(SetPage::Hash); break;
    // EST-350: the General row named "Node" opens the Node page (Name, Public key, Share position);
    // the rename is the Node page's own "Name" row (A_NodeName), which is what used to be here.
    case A_Node:     setGo(SetPage::Node); break;
    // EST-392: the ONE position source control. It is not a page: it opens the small GPS / Fixed
    // choice under the row, lifted just enough for the whole panel to be on the glass.
    case A_PosSource:
      g_posChoice = true;
      g_setSelOpen = false;
      g_setScroll = om::ui::settingsChoiceScrollFor(
          om::ui::settingsLayoutFor(om::ui::kScreenW, om::ui::kScreenH, g_setSubPage), g_setRows,
          g_setRowCount, g_posRowIndex, g_setScroll);
      break;
    case A_NodeName:
      snprintf(g_editBuf, sizeof(g_editBuf), "%s", om::meshNodeName());
      s_setNameNode = true;
      g_editNew = false;
      setGo(SetPage::NameEdit);
      break;
    // EST-350: the "THIS CHAT" header opens the chat selector (setGo would close it, so it is not
    // used here: the page does not change). Opening it puts the page back at the top, so the header
    // row is exactly where the dropdown hangs from.
    case A_ChatPick:
      g_setSelOpen = !g_setSelOpen;
      g_setSelScroll = 0;
      g_setScroll = 0;
      g_ask.close();
      break;
    case A_Channels: setGo(SetPage::Channels); break;
    case A_Wifi:     setGo(SetPage::Wifi); break;
    case A_WifiToggle: {
      // EST-422: a switch that matters, so the sheet asks first. The value does not move here.
      const bool on = !om::wifiIsEnabled();
      askChange(om::ui::ConfirmKind::WifiSwitch, on ? 1 : 0, on ? "on" : "off");
      break;
    }
    case A_WifiScan:
      if (!om::wifiIsEnabled()) {
        showToast("Wi-Fi is off");
      } else {
        om::wifiStartScan();
      }
      break;
    case A_WifiSaved: setGo(SetPage::WifiSaved); break;
    case A_Bt:       setGo(SetPage::Bt); break;
    case A_BtToggle: {
      // EST-422: asks first. The old toast rule stays in the apply below.
      const bool on = !om::bleIsEnabled();
      askChange(om::ui::ConfirmKind::BtSwitch, on ? 1 : 0, on ? "on" : "off");
      break;
    }
    case A_BtNewPin: {
      const uint32_t pin = om::bleNewPin();
      showToast(pin != 0 ? "New PIN saved" : "New PIN failed");
      break;
    }
    // EST-412: the Grove keyboard switch. EST-422: it asks first, because switching it on powers the
    // Grove rail. The apply below does the work: RAM first, NVS after (a failed write is said out
    // loud but does not undo the switch). ON opens cardkb::begin()'s start window; OFF cancels a
    // window still running, closes the bus and drops the 5 V rail.
    case A_GroveKeyboard: {
      const bool on = !g_kbEnabled;
      askChange(om::ui::ConfirmKind::KeyboardSwitch, on ? 1 : 0, on ? "on" : "off");
      break;
    }
    case A_Sound:    setGo(SetPage::Sound); break;
    case A_Time:     setGo(SetPage::Time); break;
    // EST-405: the switch. Both stores move together: the saved one writes ONLY when the value
    // changes (the store's own rule), the live one restarts the count from now. Switching on leaves
    // the time at its saved value, which is 1 min on a fresh install (the ticket's default).
    case A_IdleAutoOff: {
      const bool on = !g_idle.enabled();
      const bool saved = g_idlePrefs.setEnabled(on);
      g_idle.setEnabled(on, millis());
      if (!saved) showToast("Auto-off setting not saved");
      Serial.printf("[idle] screen auto-off %s, %s\n", on ? "on" : "off", g_idle.timeLabel());
      break;
    }
    case A_IdleTime: setGo(SetPage::AutoOff); break;
    case A_TimeManual:
      timeInitFromClock();
      setGo(SetPage::TimeEdit);
      break;
    case A_AdvertPos: {
      const bool on = !om::meshAdvertPosPolicyGet();
      om::meshAdvertPosPolicySet(on);
      showToast(on ? "Position shared in adverts" : "Position not shared");
      break;
    }

    case A_MapRecentre:
      om::mapSetView(46.0569, 14.5058, 13);
      showToast("Map recentred");
      break;
    case A_MapClear:
      om::mapClearMarker();
      showToast("Marker cleared");
      break;
    case A_RptrForget: {
      // Forget the open repeater, or the last remembered one when the tab has none open. EST-422: the
      // sheet asks first and carries the name; the apply does the logging out.
      const char* openName = om::rptr_tab::openNodeName();
      const char* name = openName[0] ? openName : om::rptrLastRemembered();
      if (name != nullptr && name[0]) {
        askChange(om::ui::ConfirmKind::RepeaterForget, 0, name);
      }
      break;
    }
    case A_RptrAuto:
      om::rptrSetAutoLogin(!om::rptrAutoLogin());
      showToast(om::rptrAutoLogin() ? "Auto-login on" : "Auto-login off");
      break;
    case A_RptrOpen:
      // EST-414: leave Settings and show the RPTR tab as it stands. The tab's own state is NOT reset,
      // so the open session's page (the view login left behind) is exactly what comes back. Settings
      // clears its transient state first, through the same helper Back uses.
      settingsLeaveState();
      if (g_tab == 3) redrawMainTab();   // already the RPTR tab: repaint it in place
      else showTab(3);                   // the screen change composes and pushes it
      return;

    // Chat tab: the same channel, reached from the open chat.
    case A_ChatOpen:
      if (ch >= 0) openChannelPage(ch);
      return;
    case A_ChatEnabled:
      if (ch >= 0) {
        om::mcChannelSetEnabled(ch, !om::mcChannelEnabled(ch));
      }
      break;
    case A_ChatSound:
      if (ch >= 0) {
        om::mcChannelSetMuted(ch, !om::mcChannelMuted(ch));
      }
      break;
    case A_ChatRename:
      if (ch >= 0) {
        s_setNameNode = false;
        g_editNew = false;
        g_editCh = ch;
        snprintf(g_editBuf, sizeof(g_editBuf), "%s", om::mcChannelName(ch));
        setGo(SetPage::NameEdit);
      }
      break;
    case A_ChatDelete:
      if (ch >= 0) {
        // EST-422: the shared sheet asks; the apply removes the channel (EST-399's second tap is gone,
        // so every delete in the app asks the same way).
        askChange(om::ui::ConfirmKind::ChannelDelete, ch, om::mcChannelName(ch));
      }
      break;
    case A_ChatMsgSound: openSoundPicker(SoundEvent::Message); return;
    case A_ChatDmSound:  openSoundPicker(SoundEvent::Dm); return;
    case A_ChatMenSound: openSoundPicker(SoundEvent::Mention); return;

    case A_SoundMaster:
      om::sounds::setMasterOn(!om::sounds::masterOn());
      om::sounds::save();
      if (om::sounds::masterOn()) om::sounds::play(SoundEvent::Message, om::sounds::choice(SoundEvent::Message), true);
      break;
    case A_SoundBoot: openSoundPicker(SoundEvent::Boot); return;
    case A_SoundMsg:  openSoundPicker(SoundEvent::Message); return;
    case A_SoundDm:   openSoundPicker(SoundEvent::Dm); return;
    case A_SoundMen:  openSoundPicker(SoundEvent::Mention); return;
    case A_SoundSent: openSoundPicker(SoundEvent::Sent); return;
    case A_SoundError: openSoundPicker(SoundEvent::Error); return;
    case A_SoundNew:  openSoundPicker(SoundEvent::NewNode); return;
    case A_SoundBatt: openSoundPicker(SoundEvent::LowBattery); return;
    case A_SoundClick: openSoundPicker(SoundEvent::Touch); return;
    case A_SoundTouch:
      om::sounds::setTouchClicks(!om::sounds::touchClicks());
      om::sounds::save();
      if (om::sounds::touchClicks()) om::sounds::play(SoundEvent::Touch, om::sounds::choice(SoundEvent::Touch), true);
      break;
    case A_SoundDnd:
      om::sounds::setDnd(!om::sounds::dnd());
      om::sounds::save();
      break;
    case A_SoundWelcome:
      om::sounds::setWelcome(!om::sounds::welcome());
      om::sounds::save();
      if (om::sounds::welcome()) om::sounds::play(SoundEvent::Boot, om::sounds::choice(SoundEvent::Boot), true);
      break;

    case A_SoundPickUse: {
      const SoundEvent ev = (SoundEvent)g_setSoundEvent;
      if (g_setSoundPending != (int)om::sound::kSoundOff &&
          !om::sound::soundIsCurrent((uint8_t)g_setSoundPending)) {
        g_setSoundPending = (int)om::sound::defaultSound(ev);
      }
      om::sounds::choice(ev) = (uint8_t)g_setSoundPending;
      om::sounds::save();
      setBack();                    // the picker's opener: Sound, or the Chat page it came from
      showToast("Sound saved");
      break;
    }

    case A_ChanAdd:
      setGo(SetPage::ChanAdd);
      break;
    case A_AddCreate:
    case A_AddPrivate:
    case A_AddHashtag:
      g_addKind = id == A_AddCreate ? 1 : (id == A_AddPrivate ? 2 : 3);
      g_editNew = true;
      s_setNameNode = false;
      g_editBuf[0] = 0;
      setGo(SetPage::NameEdit);
      break;
    case A_AddPublic: {
      const int slot = om::mcChannelAdd("Public", om::mcPublicPsk());
      if (slot >= 0) {
        om::meshLinkReloadChannels();
        openChannelPage(slot);
        return;
      }
      showToast("Channel table is full");
      break;
    }

    case A_ChanRename:
      s_setNameNode = false;
      g_editNew = false;
      g_editCh = g_chanPage;
      snprintf(g_editBuf, sizeof(g_editBuf), "%s", om::mcChannelName(g_chanPage));
      setGo(SetPage::NameEdit);
      break;
    case A_ChanEnabled:
      om::mcChannelSetEnabled(g_chanPage, !om::mcChannelEnabled(g_chanPage));
      break;
    case A_ChanSound:
      om::mcChannelSetMuted(g_chanPage, !om::mcChannelMuted(g_chanPage));
      break;
    case A_ChanClear:
      // EST-382's question, now the shared sheet (EST-422). Cancel is the default side; only the
      // sheet's Clear calls meshChatClear(). The name in the question is the channel's own.
      askChange(om::ui::ConfirmKind::ClearMessages, (int)g_chanPage, om::mcChannelName(g_chanPage));
      break;
    case A_ChanDelete:
      // EST-422: the same shared sheet every delete uses. The apply removes the channel and steps back.
      askChange(om::ui::ConfirmKind::ChannelDelete, (int)g_chanPage, om::mcChannelName(g_chanPage));
      break;

    case A_CustomOpen:
      g_custom = g_radio.prefs();   // the Custom page opens on the live values
      setGo(SetPage::PresetCustom);
      break;
    case A_CustomApply:
      askChange(om::ui::ConfirmKind::Preset, om::ui::kRadioCustomPreset, "the custom values");
      break;
    case A_TimeApply:
      // EST-400: the one apply (it shows the one toast too); on success leave the page.
      if (applyManualTime()) setBack();
      break;
    case A_Apply:
      // EST-422: the preset and path-hash pages are gone (they asked through the shared sheet), so
      // these two ids have no row left that reaches them. Kept so the enum and the switch stay in
      // step with ui/settings_actions.h.
      break;
    case A_Cancel:
      break;

    default:
      if (id >= A_WifiNetBase && id < A_WifiNetBase + 8) {
        const int at = (int)(id - A_WifiNetBase);
        const om::wifi::ScanResult* n = om::wifiScanAt(at);
        if (n != nullptr) {
          const int saved = om::wifiSavedIndexFor(n->ssid);
          if (saved >= 0) {
            if (om::wifiConnectSaved(saved)) showToast("Wi-Fi: connecting");
            else showToast("Wi-Fi: not started");
          } else if (!n->secured) {
            if (om::wifiConnect(n->ssid, "")) showToast("Wi-Fi: connecting");
            else showToast("Wi-Fi: not started");
          } else {
            snprintf(g_wifiPassSsid, sizeof(g_wifiPassSsid), "%s", n->ssid);
            setGo(SetPage::WifiPass);
          }
        }
      } else if (id >= A_WifiForgetBase && id < A_WifiForgetBase + om::wifi::kMaxSaved) {
        const int at = (int)(id - A_WifiForgetBase);
        // EST-422: one shared confirm sheet per Forget row, and it names the network, so the row that
        // was tapped and the row that is asked about can never differ (EST-398 #1's failure mode).
        const om::wifi::SavedNetwork* n = om::wifiSavedAt(at);
        if (n != nullptr) askChange(om::ui::ConfirmKind::WifiForget, at, n->ssid);
      } else if (id >= A_PresetBase && id < A_PresetBase + om::ui::kRadioPresetCount) {
        // EST-422: the sheet asks "Change region to X?" on the row itself.
        const int idx = (int)(id - A_PresetBase);
        askChange(om::ui::ConfirmKind::Preset, idx, om::ui::radioPresetAt(idx).name);
      } else if (id >= A_HashBase && id < A_HashBase + 3) {
        char v[8];
        snprintf(v, sizeof(v), "%uB", (unsigned)(id - A_HashBase) + 1);
        askChange(om::ui::ConfirmKind::PathHash, (int)(id - A_HashBase) + 1, v);
      } else if (id >= A_PickBase && id < A_ChanBase) {
        const SoundEvent ev = (SoundEvent)g_setSoundEvent;
        const int count = om::sound::libraryCount();
        const int idx = (int)(id - A_PickBase);
        if (idx >= 0 && idx < count) {
          const uint8_t soundId = om::sound::libraryId(idx);
          g_setSoundPending = (int)soundId;
          om::sounds::play(ev, soundId, true);   // preview ignores DND, not master
        } else if (idx == count) {
          g_setSoundPending = (int)om::sound::kSoundOff;   // the Off row
        }
      } else if (id >= A_ChanBase && id < A_ChanBase + om::kMaxChannels) {
        openChannelPage((int)(id - A_ChanBase));
        return;
      } else if (id >= A_IdleTimeBase && id < A_IdleTimeBase + om::kIdleTimeCount) {
        // EST-405: a time choice. The store writes ONLY when the index changes; the live timer
        // restarts its count from now. The page stays open with the dot moved, like every other
        // Check list, and Back returns to General.
        const int choice = (int)(id - A_IdleTimeBase);
        const bool saved = g_idlePrefs.setTimeIndex(choice);
        g_idle.setTimeoutIndex(choice, millis());
        if (!saved) showToast("Auto-off time not saved");
        Serial.printf("[idle] auto-off after %s\n", g_idle.timeLabel());
      }
      break;
  }
  drawSettings();
}

// The +/- keys of a stepper row.
static void handleSettingsStep(uint16_t id, int dir) {
  if (dir == 0) return;
  switch (id) {
    case A_TxPower: {
      // EST-422: the stepper's +/- asks first; the row keeps showing the stored value until Apply.
      const int tx = (int)g_radio.prefs().tx + dir;
      const int next = (int)om::ui::clampTxPower(tx);
      if (next == (int)g_radio.prefs().tx) break;   // already at the end: nothing to ask
      char v[16];
      snprintf(v, sizeof(v), "%d dBm", next);
      g_ask.begin(om::ui::ConfirmKind::TxPower, next, v);
      break;
    }
    case A_SoundVolume: {
      int v = (int)om::sounds::volume() + dir * 10;
      if (v < 0) v = 0;
      if (v > 100) v = 100;
      om::sounds::setVolume((uint8_t)v);
      om::sounds::save();
      om::audioVolume(om::sounds::volume());
      break;
    }
    case A_Brightness: {
      int b = (int)g_setBrightness + dir * 20;
      if (b < 20) b = 20;
      if (b > 255) b = 255;
      g_setBrightness = (uint8_t)b;
      om::boardSetBrightness(g_setBrightness);
      g_prefs.putUChar("bright", g_setBrightness);
      break;
    }
    case A_CustomFreq: {
      int64_t f = (int64_t)g_custom.freqKhz + (int64_t)dir * 100;
      if (f < (int64_t)om::ui::kRadioFreqMin) f = om::ui::kRadioFreqMin;
      if (f > (int64_t)om::ui::kRadioFreqMax) f = om::ui::kRadioFreqMax;
      g_custom.freqKhz = (uint32_t)f;
      break;
    }
    case A_CustomBw: {
      static const uint32_t kBandwidths[] = {7800,  10400, 15600, 20800, 31250,
                                             41700, 62500, 125000, 250000, 500000};
      int at = (int)(sizeof(kBandwidths) / sizeof(kBandwidths[0])) - 1;
      for (int i = 0; i < (int)(sizeof(kBandwidths) / sizeof(kBandwidths[0])) - 1; ++i) {
        if (g_custom.bwHz <= kBandwidths[i]) { at = i; break; }
      }
      at += dir;
      if (at < 0) at = 0;
      if (at > (int)(sizeof(kBandwidths) / sizeof(kBandwidths[0])) - 1) {
        at = (int)(sizeof(kBandwidths) / sizeof(kBandwidths[0])) - 1;
      }
      g_custom.bwHz = kBandwidths[at];
      break;
    }
    case A_CustomSf: {
      int s = (int)g_custom.sf + dir;
      if (s < (int)om::ui::kRadioSfMin) s = om::ui::kRadioSfMin;
      if (s > (int)om::ui::kRadioSfMax) s = om::ui::kRadioSfMax;
      g_custom.sf = (uint8_t)s;
      break;
    }
    case A_CustomCr: {
      int c = (int)g_custom.cr + dir;
      if (c < (int)om::ui::kRadioCrMin) c = om::ui::kRadioCrMin;
      if (c > (int)om::ui::kRadioCrMax) c = om::ui::kRadioCrMax;
      g_custom.cr = (uint8_t)c;
      break;
    }
    default:
      if (id >= A_TimeFieldBase && id < A_TimeFieldBase + (uint16_t)om::ui::TimeField::Count) {
        g_setTime = om::ui::stepCivilTime(g_setTime, (om::ui::TimeField)(id - A_TimeFieldBase), dir);
      }
      break;
  }
  drawSettings();
}

static void settingsEditorOk() {
  if (g_setPage == SetPage::WifiPass) {
    char ssid[om::wifi::kSsidBytes + 1];
    snprintf(ssid, sizeof(ssid), "%s", g_wifiPassSsid);
    const char* toast = "Wi-Fi: not started";
    if (!om::wifiIsEnabled()) {
      toast = "Wi-Fi is off";
    } else if (ssid[0] == 0) {
      toast = "No network chosen";
    } else if (om::wifiConnect(ssid, g_editBuf)) {
      toast = "Wi-Fi: connecting";
    }
    // The passphrase is never needed by the screen after this point; the saved copy is what
    // auto-connect uses. Wipe both the working buffer and the display copy, then leave the sheet
    // BEFORE the toast redraws, so the page behind it is the one that appears.
    memset(g_editBuf, 0, sizeof(g_editBuf));
    g_setEditText[0] = 0;
    setBack();
    showToast(toast);
    return;
  }

  if (g_setPage == SetPage::TimeEdit) {
    // EST-400: the same one apply as the title row's Set key.
    if (applyManualTime()) setBack();   // the page that opened the editor: Time
    drawSettings();
    return;
  }

  if (g_setPage == SetPage::NameEdit) {
    if (s_setNameNode) {
      // EST-422: the node name is a setting that matters, so OK asks in the shared sheet and only its
      // Apply writes the name. Cancel leaves the page as it is and the stored name untouched.
      g_ask.begin(om::ui::ConfirmKind::NodeName, 0, g_editBuf);
    } else if (g_editNew) {
      if (g_addKind == 2) {   // join private: ask for the key next
        g_keyText[0] = 0;
        setGo(SetPage::ChanKey);
      } else {
        const int slot = g_addKind == 1 ? om::mcChannelCreatePrivate(g_editBuf)
                                        : om::mcChannelAddHashtag(g_editBuf);
        if (slot >= 0) {
          om::meshLinkReloadChannels();
          refreshChats();
          g_chanPage = slot;
          setGo(SetPage::Channel);
          showToast("Channel added");
        } else {
          showToast("Channel not added");
          setBack();                // back to Add channel, where the kind was chosen
        }
      }
    } else {
      om::mcChannelSetName(g_editCh, g_editBuf);
      g_chanPage = g_editCh;
      setBack();                    // EST-350: back to the Channel page
      showToast("Channel renamed");
    }
    drawSettings();
    return;
  }

  if (g_setPage == SetPage::ChanKey) {
    const int slot = om::mcChannelAddFromB64(g_editBuf, g_keyText);
    if (slot >= 0) {
      om::meshLinkReloadChannels();
      refreshChats();
      g_chanPage = slot;
      setGo(SetPage::Channel);
      showToast("Channel joined");
    } else {
      showToast("That key is not a 16-byte base64 key");
    }
    drawSettings();
    return;
  }
}

// EST-382: what the pop-up's Clear does. The facade removes the chat's card copy, its queued records,
// its arrival-ring entries and its unread count; this only drops the open chat's own view so the next
// frame reloads an empty chat. On a card failure the facade has already left RAM as the card is, and
// the pop-up result says so (no unread/ring reset here either).
static void settingsClearChannelMessages() {
  const int ch = g_chanPage;
  if (ch < 0 || ch >= om::mcChannelCount()) return;
  const int r = om::meshChatClear(ch);
  if (r == 2) {
    showToast("Could not clear the card copy");
  } else if (r < 0) {
    showToast("No such channel");
  } else {
    showToast("Messages cleared");
    g_chatShown[ch] = ChatShown{};
    if (g_viewChat == ch) {
      g_viewCount = 0;
      g_viewLoading = true;
      g_viewMore = true;
    }
    if (g_chatSel == ch) {
      g_chatScroll = 0;
      g_replySeq = 0;
      g_replyName[0] = 0;
      g_bubMenuSeq = 0;
    }
  }
  refreshChats();
}

// EST-422: the Apply side of the one shared confirm sheet. Every change that asked runs here, and only
// here: Cancel and a tap outside never reach this function (ui/settings_actions.h confirmTap). Each
// case is the code the row used to run straight from its tap, moved behind the sheet.
static void settingsApplyConfirmed(om::ui::ConfirmKind kind, int arg, const char* value) {
  switch (kind) {
    case om::ui::ConfirmKind::Preset:
      if (arg == om::ui::kRadioCustomPreset) {
        if (g_radio.setRadio(g_custom.freqKhz, g_custom.bwHz, g_custom.sf, g_custom.cr)) {
          g_custom = g_radio.prefs();
          showToast("Radio preset saved");
        } else {
          showToast("Preset refused");
        }
      } else if (g_radio.setPreset(arg)) {
        g_custom = g_radio.prefs();
        showToast("Radio preset saved");
      } else {
        showToast("Preset refused");
      }
      break;
    case om::ui::ConfirmKind::TxPower:
      g_radio.setTx((int8_t)om::ui::clampTxPower(arg));
      break;
    case om::ui::ConfirmKind::PathHash:
      if (om::meshPathHashSet((uint8_t)arg)) showToast("Path hash saved");
      else showToast("Path hash refused");
      break;
    case om::ui::ConfirmKind::NodeName:
      om::meshNodeNameSet(value);
      showToast("Name saved");
      setBack();                    // EST-350: back to the Node page, not to General
      break;
    case om::ui::ConfirmKind::ChannelDelete:
      om::mcChannelRemove(arg);
      om::meshLinkReloadChannels();
      refreshChats();
      showToast("Channel removed");
      if (g_setPage == SetPage::Channel) {
        setBack();                  // whichever page the channel was opened from
      } else {
        g_setChat = g_chatCount > 0 ? (g_setChat < g_chatCount ? g_setChat : 0) : 0;
        g_setPage = SetPage::ChatRoot;
        g_setScroll = 0;
      }
      break;
    case om::ui::ConfirmKind::WifiForget:
      om::wifiForget(arg);
      showToast("Network forgotten");
      break;
    case om::ui::ConfirmKind::RepeaterForget: {
      om::rptrForget(value);
      const char* openName = om::rptr_tab::openNodeName();
      if (value != nullptr && openName[0] && strcmp(value, openName) == 0) {
        om::rptrLogout();
        om::rptr_tab::clearSession();
      }
      showToast("Repeater forgotten");
      break;
    }
    case om::ui::ConfirmKind::WifiSwitch:
      om::wifiSetEnabled(arg != 0);
      showToast(arg != 0 ? "Wi-Fi on" : "Wi-Fi off");
      break;
    case om::ui::ConfirmKind::BtSwitch: {
      const bool on = arg != 0;
      om::bleSetEnabled(on);
      // EST-357: the start guard may have refused (not enough internal RAM); its own notice already
      // carries the numbers, so "Bluetooth on" must not overwrite it with a claim that is not true.
      if (!on) {
        showToast("Bluetooth off");
      } else if (om::bleIsEnabled()) {
        showToast("Bluetooth on");
      }
      break;
    }
    case om::ui::ConfirmKind::KeyboardSwitch: {
      g_kbEnabled = arg != 0;
      const bool saved = mapLayerPrefWrite(nullptr, "grovekb", g_kbEnabled);
      if (!saved) showToast("Keyboard setting not saved");
      Serial.printf("[kb] switch %s (saved=%d)\n", g_kbEnabled ? "on" : "off", saved ? 1 : 0);
      if (g_kbEnabled) {
        if (!om::cardkb::begin()) showToast("Grove power failed");
      } else {
        om::cardkb::end();
      }
      break;
    }
    case om::ui::ConfirmKind::Position:
      // 0 is GPS, 1 the point picked on the map (still in g_ownPickLatE6/g_ownPickLonE6).
      if (arg == 0) {
        if (om::posSelectGps()) showToast("Position: GPS");
      } else if (om::posSelectFixed((double)g_ownPickLatE6 / 1e6, (double)g_ownPickLonE6 / 1e6)) {
        showToast("Fixed position saved");
      } else {
        showToast("Position not saved");
      }
      g_ownPick = false;
      break;
    case om::ui::ConfirmKind::ClearMessages:
      settingsClearChannelMessages();
      break;
    case om::ui::ConfirmKind::None:
    default:
      break;
  }
}

// A tap on a settings page. All rectangles come from the view the drawing used.
static void handleSettingsTap(int x, int y) {
  // EST-384: the own-position picker owns every tap while it is up (Cancel, zoom, GPS, Save, map).
  if (g_ownPick) {
    ownPickTap(x, y);
    return;
  }
  buildSettingsRows();
  const om::ui::SettingsView v = settingsView();

  // EST-422: the ONE confirm sheet is the highest layer and owns every tap, including Back and the
  // rows behind it. Cancel and a tap outside the box change NOTHING and are consumed.
  if (g_ask.open) {
    const om::ui::SettingsModalHit h = om::ui::settingsAskHit(v, x, y);
    om::ui::ConfirmAsk answered = g_ask;   // answer() closes g_ask; arg/value stay readable here
    const om::ui::ConfirmKind k = g_ask.answer(h);
    if (k != om::ui::ConfirmKind::None) {
      Serial.printf("[set] confirm: apply kind %d\n", (int)k);
      settingsApplyConfirmed(k, answered.arg, answered.value);
    } else {
      Serial.println("[set] confirm: cancelled");
    }
    drawSettings();
    return;
  }

  // EST-392: the Position choice owns every tap while it is down, Back and the row above it
  // included. GPS asks in the shared sheet; Fixed opens EST-384's map picker exactly as before; a tap
  // anywhere else is Cancel and changes neither the source nor the saved point.
  if (g_posChoice) {
    const int option = om::ui::settingsPositionChoiceHit(v, x, y);
    g_posChoice = false;
    switch (om::ui::posChoiceAction(option)) {
      case om::ui::PosChoiceAct::Gps:
        askChange(om::ui::ConfirmKind::Position, 0, "GPS");
        break;
      case om::ui::PosChoiceAct::OpenPicker:
        // Already Fixed? Then the picker opens on the saved point, exactly like EST-384's Change row.
        ownPickOpen(om::posSource().sourceFixed());
        return;   // ownPickOpen drew the picker
      case om::ui::PosChoiceAct::Keep:
      default:
        break;    // Cancel: nothing is written
    }
    drawSettings();
    return;
  }

  // EST-350: while the chat selector is open it owns the page, exactly like the Chat tab's dropdown:
  // a row picks that chat (the page below shows its settings without leaving Settings), the pinned
  // row opens the channel list, and a tap anywhere else — including Back — closes it and is CONSUMED,
  // so the press never reaches the row behind it.
  if (g_setSelOpen) {
    const om::ui::SelectorPress press = om::ui::settingsSelectorPress(v, x, y);
    if (press.picks) {
      const int wasOpen = g_chatSel;
      om::ui::selectorPickShown(press, &g_setChat);   // g_chatSel is deliberately untouched
      g_setSelOpen = false;
      g_setScroll = 0;
      g_ask.close();
      // EST-399: which chat was picked (its index), never its name (rule 9).
      Serial.printf("[set] chat picked: %d of %d (chat screen still on %d)\n", g_setChat, g_chatCount,
                    wasOpen);
      drawSettings();
      return;
    }
    if (press.kind == om::ui::SelectorHitKind::Manage) {
      g_setSelOpen = false;
      openChannelList();
      return;
    }
    g_setSelOpen = false;
    drawSettings();
    return;                   // consumed: no tap behind a closed dropdown
  }

  if (om::ui::settingsBackHit(v, x, y)) {
    settingsBack();
    return;
  }

  // EST-363: the title row's commit action (the picker's Use, the time page's Set, the custom preset's
  // Apply). It is drawn dim when there is nothing new to commit, and then a tap does nothing at all
  // but is still spent here, so it can never fall through to a row behind it.
  if (om::ui::settingsTitleActionHit(v, x, y)) {
    if (g_setActionOn) handleSettingsRow(g_setActionId);
    return;
  }

  if (g_setEditor != om::ui::SettingsEditor::None) {
    // EST-352: the sheet owns the page. One key, one action, through the same key tables and byte
    // filters the chat uses. A tap above the sheet (the hint line) does nothing, and Back above it
    // was handled before this branch.
    const om::ui::SettingsKeyHit key = om::ui::settingsEditorKeyAt(v, x, y);
    if (!key.pressed) return;
    switch (key.kind) {
      case om::ui::KeyKind::Shift:
        g_setEditShift = !g_setEditShift;
        break;
      case om::ui::KeyKind::Mode:
        g_setEditNums = !g_setEditNums;
        g_setEditShift = false;
        break;
      case om::ui::KeyKind::Del:
        om::ui::composeBackspace(settingsEditBuf());   // one whole code point, never half an accent
        break;
      case om::ui::KeyKind::Reveal:
        g_setEditReveal = !g_setEditReveal;   // EST-354: show/hide the passphrase
        break;
      case om::ui::KeyKind::Send:
        settingsEditorOk();   // draws its own frame
        return;
      case om::ui::KeyKind::Space:
        settingsEditAppendChar(' ');
        break;
      case om::ui::KeyKind::Char:
        settingsEditAppendChar(key.ch);
        break;
      case om::ui::KeyKind::Emoji:
      default:
        break;   // an editor's sheet offers no emoji page
    }
    drawSettings();
    return;
  }

  const int tab = om::ui::settingsTabHit(v, x, y);
  if (tab >= 0) {
    g_setTab = (om::ui::SettingsTab)tab;
    g_setPage = setRootForTab(g_setTab);
    g_setScroll = 0;
    g_setNav.reset();         // a tab is a new root: Back leaves Settings from it
    g_ask.close();
    g_posChoice = false;      // EST-392: a tab is a new page, so no choice is left down
    drawSettings();
    return;
  }

  const int row = om::ui::settingsRowHit(v, x, y);
  if (row < 0) return;
  const int part = om::ui::settingsStepperHit(v, x, y);
  if (part != 0) {
    handleSettingsStep(g_setRows[row].id, part);
    return;
  }
  handleSettingsRow(g_setRows[row].id);
}

// The two MeshCore-backed callbacks the radio store calls. Nothing here is a second store: the read
// comes from NodePrefs and the write is the same savePrefs + radio apply the phone commands use.
static bool radioPrefsRead(void*, om::ui::RadioPrefs& out) {
  om::MeshRadioPrefs p;
  if (!om::meshRadioPrefsGet(&p)) return false;
  out.freqKhz = p.freq_khz;
  out.bwHz = p.bw_hz;
  out.sf = p.sf;
  out.cr = p.cr;
  out.tx = p.tx;
  return true;
}

static bool radioPrefsWrite(void*, const om::ui::RadioPrefs& p) {
  om::MeshRadioPrefs m{p.freqKhz, p.bwHz, p.sf, p.cr, p.tx};
  return om::meshRadioPrefsSet(m);
}

static void settingsBegin() {
  g_radio.begin(radioPrefsRead, radioPrefsWrite, nullptr);
  const bool seeded = g_radio.load();
  g_custom = g_radio.prefs();
  if (seeded) Serial.println("[set] radio prefs seeded from the build values");
}

