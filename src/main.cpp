// mesh is down or nothing has been heard yet; 0 is a real answer and draws the empty state.

static int batteryPercent(uint16_t mv) {
  if (mv == 0) return -1;
  // Single-cell Li-ion estimate. The board reports volts; there is no fuel gauge. 3.2 V empty,
  // 4.2 V full (4.139 V measured on the device maps to 93%).
  int pct = ((int)mv - 3200) / 10;
  if (pct < 0) pct = 0;
  if (pct > 100) pct = 100;
  return pct;
}

static int unreadTotal() {
  int n = 0;
  for (int i = 0; i < om::mcChannelCount(); ++i) n += om::meshUnread(i);
  return n;
}

static void refreshNodes() {
  // Static, not stack: 64 x ContactInfo-sized copies would eat ~3 KB of the loop task's stack.
  static om::MeshContact list[64];
  const int n = om::meshContactList(list, 64);
  const uint32_t now = om::meshNow();
  g_nodeCount = n;
  for (int i = 0; i < n; ++i) {
    om::ui::NodeItem& it = g_nodes[i];
    snprintf(it.name, sizeof(it.name), "%s", list[i].name);
    switch (list[i].type) {
      case 1: it.type = om::ui::NodeType::Client; break;     // ADV_TYPE_CHAT
      case 2: it.type = om::ui::NodeType::Repeater; break;   // ADV_TYPE_REPEATER
      case 3: it.type = om::ui::NodeType::Room; break;       // ADV_TYPE_ROOM
      case 4: it.type = om::ui::NodeType::Sensor; break;     // ADV_TYPE_SENSOR
      default: it.type = om::ui::NodeType::Unknown; break;
    }
    // MeshCore's contact record has no RSSI, so no signal bars are claimed for a contact.
    it.rssi = om::ui::kNoRssi;
    if (list[i].path_len == 0) snprintf(it.note, sizeof(it.note), "direct");
    else if (list[i].path_len == 0xFF) snprintf(it.note, sizeof(it.note), "path --");
    else snprintf(it.note, sizeof(it.note), "path %uB", (unsigned)list[i].path_len);
    om::ui::ageText(it.age, sizeof(it.age), list[i].lastmod, now, g_buildEpoch);
  }
  if (g_nodeSel >= n) g_nodeSel = n - 1;
  const int maxScroll = om::ui::l2().maxScroll(n);
  if (g_nodeScroll > maxScroll) g_nodeScroll = maxScroll;
  if (g_nodeScroll < 0) g_nodeScroll = 0;
}

static void buildStatus(om::ui::StatusModel& s) {
  s = om::ui::StatusModel();
  s.meshReady = om::meshLinkReady();
  s.nodes = g_nodeCount;
  s.gpsValid = g_gps.valid;
  s.gpsSats = g_gps.sats;
  s.gpsHeard = g_gps.heardTotal;
  s.gpsTalked = g_gps.sentences > 0;
  s.batteryPct = batteryPercent(g_battMv);
  // Data honesty: show HH:MM only after a real source (GPS today) has set the clock since boot.
  // Before that the time is only the floor (max saved, build time), which is not a real time.
  static char clockText[8];
  if (om::timeKeeper().realSinceBoot()) {
    om::formatClock(om::timeKeeper().now(), clockText, sizeof(clockText));
    s.clock = clockText;
  } else {
    s.clock = "--:--";
  }
}

