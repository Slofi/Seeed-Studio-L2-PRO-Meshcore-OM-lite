// The draft budget of the open chat. A channel text spends our "<name>: " prefix (and an "@Name "
// reply mention); a direct text frame spends only its 4-byte timestamp and 1 attempt byte, so the DM
// budget is MAX_TEXT_LEN minus five (mesh_text.h, proven by the host test).
static int chatDraftAllowance() {
  if (chatThread(g_chatSel) >= 0) return om::kMeshDmTextMax;
  const bool replying = g_replySeq != 0 && g_replyName[0] != 0;
  return om::ui::composeAllowance(replying, g_replyName, om::meshNodeName());
}

// Send on the open chat. A channel reply travels as "@Name text": MeshCore's message format has no
// reply field (checked in Packet/BaseChatMesh), and the mention is what the bots already understand.
// A DM has exactly one reader, so its reply bar marks what the text answers without adding bytes to
// the frame. Nothing is cut here: an over-long draft is refused and logged instead of going on the
// air short (EST-334).
static bool chatSend() {
  if (g_kbText[0] == 0) return false;
  const int allow = chatDraftAllowance();
  if ((int)strlen(g_kbText) > allow) {
    Serial.printf("[chat] send refused: %u bytes, %d allowed\n", (unsigned)strlen(g_kbText), allow);
    return false;
  }
  const int thread = chatThread(g_chatSel);
  if (thread >= 0) {
    const bool sent = om::meshDmSend(thread, g_kbText);
    Serial.printf("[mc] UI DM send: %s '%s'\n", sent ? "ok" : "failed", g_kbText);
    return sent;
  }
  const int chan = chatChannel(g_chatSel);
  if (chan < 0) return false;
  const bool replying = g_replySeq != 0 && g_replyName[0] != 0;
  char wire[om::kMeshTextCap + om::kMeshNameMax + 4];
  if (replying) {
    snprintf(wire, sizeof(wire), "@%s %s", g_replyName, g_kbText);
  } else {
    snprintf(wire, sizeof(wire), "%s", g_kbText);
  }
  const bool sent = om::meshLinkSend(chan, wire);
  Serial.printf("[mc] UI send: %s '%s'\n", sent ? "ok" : "failed", wire);
  return sent;
}

// Send the draft through the open chat (channel or DM). One place for the keyboard's Send key and
// the emoji page's Send button, so both clear the same state.
static void chatSendDraft() {
  if (!chatSend()) return;
  g_kbText[0] = 0;
  g_replySeq = 0;
  g_replyName[0] = 0;
  g_kb.close();   // the next open goes through openSheet() and starts on letters, shift off
}

// One emoji from the keyboard: four UTF-8 bytes at most, refused as a unit when the draft budget
// has no room for it (never a broken sequence). The pick moves to the front of the Recent row.
static void chatEmojiPick(uint32_t cp) {
  char bytes[5] = {0};
  const int n = om::ui::utf8Encode(cp, bytes);
  if (n <= 0) return;
  bytes[n] = 0;
  if (!om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), bytes, chatDraftAllowance())) {
    Serial.printf("[chat] emoji U+%04lX refused: draft budget full\n", (unsigned long)cp);
    return;
  }
  g_emojiRecent.use(cp);
  saveEmojiRecent();
  Serial.printf("[chat] emoji U+%04lX -> recent %u\n", (unsigned long)cp,
                (unsigned)g_emojiRecent.count);
}

// EST-346: the release of a hold on s, c or z enters the accented letter the bubble showed. One code
// point (two UTF-8 bytes), appended as a whole through the same budget as every other key: a full
// draft refuses it rather than splitting the sequence.
static void chatAccentCommit() {
  if (g_accentCp == 0) return;
  char bytes[5] = {0};
  const int n = om::ui::utf8Encode(g_accentCp, bytes);
  if (n <= 0) return;
  bytes[n] = 0;
  if (!om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), bytes, chatDraftAllowance())) {
    Serial.printf("[chat] accent U+%04lX refused: draft budget full\n", (unsigned long)g_accentCp);
    return;
  }
  Serial.printf("[chat] accent U+%04lX (%s), %u bytes in the draft\n", (unsigned long)g_accentCp,
                bytes, (unsigned)strlen(g_kbText));
}

// The sheet owns the keyboard state; this applies one key and says whether the draft was sent. The
// draft counts bytes against the same budget the counter shows, and a key that would pass it does
// nothing at all (Filip, 2026-11-10: no silent cut on send).
static void chatKey(const om::ui::ChatHitResult& hit) {
  const int allow = chatDraftAllowance();
  switch (hit.keyKind) {
    case om::ui::KeyKind::Shift:
      g_kb.toggleShift();
      break;
    case om::ui::KeyKind::Mode:
      g_kb.toggleNumbers();
      break;
    case om::ui::KeyKind::Emoji:
      g_kb.toggleEmoji();
      g_emojiScroll = 0;
      break;
    case om::ui::KeyKind::Space:
      om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), " ", allow);
      break;
    case om::ui::KeyKind::Del:
      om::ui::composeBackspace(g_kbText);   // one whole code point, never half an emoji
      break;
    case om::ui::KeyKind::Send:
      chatSendDraft();
      break;
    case om::ui::KeyKind::Char: {
      char one[2] = {hit.keyCh, 0};
      if (g_kb.shift && !g_kb.nums() && one[0] >= 'a' && one[0] <= 'z') one[0] = (char)(one[0] - 32);
      om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), one, allow);
      break;
    }
  }
}

