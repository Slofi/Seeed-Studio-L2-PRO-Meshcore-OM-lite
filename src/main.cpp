static void drawChatMessages() {
  om::omFrameBegin();
  auto* d = om::om_display();
  d->fillScreen(kBg);
  drawTopBar("BACK");
  d->setTextDatum(lgfx::textdatum_t::top_left);
  d->setTextSize(1);
  d->setTextColor(kGold, kBg);
  d->drawString(om::mcChannelName(g_chatCh), 8, 36);

  // Newest first, drawn bottom-up. The stack is anchored at the bottom edge: g_chatScroll pushes it
  // DOWN, so dragging a finger down carries the messages down with it and older ones come in from
  // the top. It used to subtract, which lifted the stack instead: that is the inverted scroll.
  int total = 0;
  for (int i = 0; i < om::meshMsgCount(); ++i) {
    if (om::meshMsgChannel(i) != g_chatCh) continue;
    char tmp[kChatMaxLines][kChatCols];
    // Exactly what the draw loop consumes: bubble height plus the 4 px gap after it.
    total += 3 + kChatNameH + wrapLines(d, om::meshMsgText(i), tmp, kChatTextPx) * kChatLineH + 3 + 4;
  }
  g_chatMaxScroll = total > (kMsgBottom - kMsgTop) ? total - (kMsgBottom - kMsgTop) : 0;
  if (g_chatScroll > g_chatMaxScroll) g_chatScroll = g_chatMaxScroll;
  g_bubN = 0;
  // Bubbles are clipped to the message band, so a half-scrolled bubble cannot paint over the title
  // or the corner icon.
  d->setClipRect(0, kMsgTop, 320, kMsgBottom - kMsgTop);
  int y = kMsgBottom + g_chatScroll;
  for (int i = om::meshMsgCount() - 1; i >= 0; --i) {
    if (om::meshMsgChannel(i) != g_chatCh) continue;
    char lines[kChatMaxLines][kChatCols];
    const int n = wrapLines(d, om::meshMsgText(i), lines, kChatTextPx);
    const int h = 3 + kChatNameH + (n > 0 ? n : 1) * kChatLineH + 3;
    y -= h;
    if (y + h <= kMsgTop) break;   // above the band: so is every message older than this one
    const bool mine = om::meshMsgMine(i);
    if (y < kMsgBottom) {     // at least partly in the band (the clip trims the rest)
      // A bubble that reaches the corner icon's band stops short of it, so the icon never covers
      // the text or the age. Bubbles above the band keep the full width.
      const bool overIcon = (y + h > kKbIconY - 4) && (y < kKbIconY + kKbIconH + 4);
      const int bw = overIcon ? kNarrowBubbleW : 300;
      d->fillRoundRect(6, y, bw, h, 5, mine ? 0x39E7 : 0x2124);
      d->drawRoundRect(6, y, bw, h, 5, mine ? kGold : kDim);
      d->setTextColor(kGold);   // transparent: the bubble fill is the background
      d->drawString(om::meshMsgName(i), 12, y + 3);
      char age[8];
      fmtAge(age, sizeof(age), om::meshMsgTs(i));
      d->setTextDatum(lgfx::textdatum_t::top_right);
      d->setTextColor(kDim);
      d->drawString(age, 6 + bw - 6, y + 3);
      d->setTextDatum(lgfx::textdatum_t::top_left);
      d->setTextColor(mine ? kBg : TFT_WHITE);
      for (int r = 0; r < n; ++r) d->drawString(lines[r], 12, y + 3 + kChatNameH + r * kChatLineH);
      // Remember the box so a tap can find this message (newest is recorded first).
      if (g_bubN < (int)(sizeof(g_bubIdx) / sizeof(g_bubIdx[0]))) {
        g_bubIdx[g_bubN] = i;
        g_bubY[g_bubN] = y < kMsgTop ? kMsgTop : y;
        g_bubH[g_bubN] = (y + h) - g_bubY[g_bubN];
        ++g_bubN;
      }
    }
    y -= 4;
  }
  // Scroll indicator: a thin track with a gold thumb, drawn only when there is something to scroll.
  // The view is bottom-anchored, so scroll 0 puts the thumb at the bottom and the oldest message at the top.
  if (g_chatMaxScroll > 0 && total > 0) {
    constexpr int kBarX = 314, kBarW = 4;
    const int bandH = kMsgBottom - kMsgTop;
    d->fillRect(kBarX, kMsgTop, kBarW, bandH, 0x4A49);          // track
    int thumbH = (int)((long)bandH * bandH / total);
    if (thumbH < 16) thumbH = 16;
    if (thumbH > bandH) thumbH = bandH;
    const int off = g_chatMaxScroll - g_chatScroll;             // 0 = showing the top of the history
    const int thumbY = kMsgTop + (bandH - thumbH) * off / g_chatMaxScroll;
    d->fillRect(kBarX, thumbY, kBarW, thumbH, kGold);
  }
  d->clearClipRect();

  // The info panel covers the whole band, so the icon would only peek out from under it.
  if (g_bubInfo < 0) drawKbIcon();
  om::omFrameEnd();
}

