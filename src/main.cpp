// ---------------------------------------------------------------------------------- chat shell
// The Chat tab is the new screen (src/ui/screen_chat.cpp). This file only feeds it and reacts to what
// was tapped; every rectangle and every pixel lives in the UI layer.

// The chats are the MeshCore channels (channels first), then the direct messages the facade knows.
// A DM row exists from the moment its thread exists: a received DM, or one opened from the Nodes
// menu (EST-342), so "Direct messages" is no longer tied to having received one first.
static void refreshChats() {
  g_chatCount = 0;
  for (int i = 0; i < om::mcChannelCount() && g_chatCount < om::ui::kMaxChats; ++i) {
    om::ui::ChatEntry& c = g_chats[g_chatCount++];
    c = om::ui::ChatEntry();
    snprintf(c.name, sizeof(c.name), "%s", om::mcChannelName(i));
    const int unread = om::meshUnread(i);
    c.unread = unread > 0 ? (uint16_t)unread : 0;
    c.dm = false;
    c.muted = om::mcChannelMuted(i);
  }
  g_channelCount = g_chatCount;

  // The last message of each channel, for the selector's preview line (sender, start of text, age).
  // The ring is oldest first, so the latest write wins.
  for (int i = 0; i < om::meshMsgCount(); ++i) {
    const int chan = om::meshMsgChannel(i);
    if (chan < 0 || chan >= g_channelCount) continue;
    om::ui::ChatEntry& c = g_chats[chan];
    c.hasLast = true;
    c.lastTs = om::meshMsgTs(i);
    c.lastWall = om::meshMsgWallTs(i);
    c.lastWallReal = om::meshMsgWallReal(i);
    snprintf(c.lastFrom, sizeof(c.lastFrom), "%s", om::meshMsgName(i));
    snprintf(c.lastText, sizeof(c.lastText), "%s", om::meshMsgText(i));
  }

  // Direct messages come from the facade, never from a placeholder list. The entry keeps the thread
  // index, so the open chat and the send path never have to guess from the position in the list.
  for (int i = 0; i < om::meshDmCount() && g_chatCount < om::ui::kMaxChats; ++i) {
    om::ui::ChatEntry& c = g_chats[g_chatCount++];
    c = om::ui::ChatEntry();
    snprintf(c.name, sizeof(c.name), "DM: %s", om::meshDmName(i));
    c.dm = true;
    c.thread = i;   // threads are allocated in order and only ever added: the used ones are packed
    c.unread = (uint16_t)om::meshDmUnread(i);
    const int n = om::meshDmList(i, g_dmScratch, om::ui::kMaxChatMsgs);
    if (n > 0) {
      const om::MeshDm& last = g_dmScratch[n - 1];
      c.hasLast = true;
      c.lastTs = last.ts;
      c.lastWall = last.wall;
      c.lastWallReal = last.wallReal;
      snprintf(c.lastFrom, sizeof(c.lastFrom), "%s", last.name);
      snprintf(c.lastText, sizeof(c.lastText), "%s", last.text);
    }
  }
  g_dmCount = g_chatCount - g_channelCount;

  if (g_chatSel >= g_chatCount) g_chatSel = g_chatCount - 1;
  if (g_chatSel < 0) g_chatSel = 0;
}

// The MeshCore channel a chat entry sends to, or -1 for an entry that is not a channel (a DM).
static int chatChannel(int chat) {
  return (chat >= 0 && chat < g_channelCount) ? chat : -1;
}

// The DM thread of an open chat, or -1 for a channel / a chat with no thread.
static int chatThread(int chat) {
  if (chat < 0 || chat >= g_chatCount || !g_chats[chat].dm) return -1;
  return g_chats[chat].thread;
}

static void refreshChatMessages() {
  g_chatMsgCount = 0;
  const int chan = chatChannel(g_chatSel);
  const int thread = chatThread(g_chatSel);
  if (thread >= 0) {
    // One thread: the facade copies the ring into the shared buffer, and the view points into it
    // (stable for this draw: the mesh is not pumped between buildChatView and chatScreenDraw).
    const int n = om::meshDmList(thread, g_dmScratch, om::ui::kMaxChatMsgs);
    for (int i = 0; i < n; ++i) {
      const om::MeshDm& dm = g_dmScratch[i];
      om::ui::ChatMsgView& m = g_chatMsgs[g_chatMsgCount++];
      m.seq = dm.seq;
      m.name = dm.name;
      m.text = dm.text;
      m.chanName = "DM";
      m.ts = dm.ts;
      m.wall = dm.wall;
      m.wallReal = dm.wallReal;
      m.hops = dm.hops;
      m.snrq = dm.snr4;
      m.mine = dm.mine;
      m.dm = true;
      m.delivery = dm.state;
      m.ackWall = dm.ackWall;
      m.ackReal = dm.ackReal;
      if (dm.pathCount > 0) {
        m.path = dm.path;
        m.pathHashSize = dm.pathHashSize;
        m.pathHashCount = dm.pathCount;
      }
    }
    return;
  }
  if (chan < 0) return;
  for (int i = 0; i < om::meshMsgCount() && g_chatMsgCount < om::ui::kMaxChatMsgs; ++i) {
    if (om::meshMsgChannel(i) != chan) continue;
    om::ui::ChatMsgView& m = g_chatMsgs[g_chatMsgCount++];
    m.seq = om::meshMsgSeq(i);
    m.name = om::meshMsgName(i);
    m.text = om::meshMsgText(i);
    m.chanName = om::mcChannelName(chan);
    m.ts = om::meshMsgTs(i);
    m.wall = om::meshMsgWallTs(i);
    m.wallReal = om::meshMsgWallReal(i);
    m.hops = (int8_t)om::meshMsgHops(i);
    m.snrq = (int8_t)om::meshMsgSnrQ(i);
    m.mine = om::meshMsgMine(i);
    uint8_t hs = 1, hc = 0;
    m.path = om::meshMsgPath(i, &hs, &hc);
    m.pathHashSize = hs;
    m.pathHashCount = hc;
    m.repeats = om::meshMsgHeardRepeats(i);
  }
}

