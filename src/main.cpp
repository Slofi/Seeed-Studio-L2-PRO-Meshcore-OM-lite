  refreshChatMessages();
  v = om::ui::ChatView();
  buildStatus(v.status);
  v.chats = g_chats;
  v.chatCount = g_chatCount;
  v.channelCount = g_channelCount;
  v.dmCount = g_dmCount;
  v.selChat = g_chatSel;
  v.selScroll = g_selScroll;
  v.selector = g_selector;
  v.msgs = g_chatMsgs;
  v.msgCount = g_chatMsgCount;
  v.scroll = g_chatScroll;
  v.nowSec = millis() / 1000;
  v.nowWall = om::timeKeeper().now();
  v.nowReal = om::timeKeeper().realSinceBoot();
  v.osk = g_compose;
  v.shift = g_kbShift;
  v.nums = g_kbNums;
  v.emoji = g_kbEmoji;
