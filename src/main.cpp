static void playPattern(uint8_t idx) {
  if (!g_soundOn || g_dnd) return;
  if (idx >= kChimeCount) return;   // Off
  const Chime& c = kChimes[idx % kChimeCount];
  om::audioVolume(g_volume);
  for (uint8_t i = 0; i < c.n; ++i) om::audioTone(c.f[i], c.d[i]);
}

