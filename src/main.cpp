    d->setTextDatum(lgfx::textdatum_t::middle_center);
    d->setTextSize(1);
    d->setTextColor(on ? kGold : kDim, kBg);
    d->drawString(kTabs[i], i * kTabW + kTabW / 2, kTabY + 14);
    if (on) d->fillRect(i * kTabW + 30, kTabY + 23, kTabW - 60, 2, kGold);
