// The draft budget of the open chat. A channel text spends our "<name>: " prefix (and an "@Name "
// reply mention); a direct text frame spends only its 4-byte timestamp and 1 attempt byte, so the DM
// budget is MAX_TEXT_LEN minus five (mesh_text.h, proven by the host test).
static int chatDraftAllowance() {
  if (chatThread(g_chatSel) >= 0) return om::kMeshDmTextMax;
  const bool replying = g_replySeq != 0 && g_replyName[0] != 0;
  return om::ui::composeAllowance(replying, g_replyName, om::meshNodeName());
}

// Send on the open chat. A channel reply travels as "@Name text": MeshCore's message format has no
// reply field (checked in Packet/BaseChatMesh), and the mention is what the bots already understand.
// A DM has exactly one reader, so its reply bar marks what the text answers without adding bytes to
// the frame. Nothing is cut here: an over-long draft is refused and logged instead of going on the
// air short (EST-334).
static bool chatSend() {
  // EST-406: the send button's dim state is this same rule. A draft that is empty or only whitespace
  // has nothing to send, so neither the look nor the action may pretend otherwise.
  if (!om::ui::sendEnabled(g_kbText)) return false;
  const int allow = chatDraftAllowance();
  if ((int)strlen(g_kbText) > allow) {
    Serial.printf("[chat] send refused: %u bytes, %d allowed\n", (unsigned)strlen(g_kbText), allow);
    return false;
  }
  const int thread = chatThread(g_chatSel);
  if (thread >= 0) {
    const bool sent = om::meshDmSend(thread, g_kbText);
    if (sent) om::sounds::playEvent(SoundEvent::Sent);
    else om::sounds::playEvent(SoundEvent::Error);
    // EST-399: the verdict and the length, never the draft (rule 9; EST-396 #2).
    Serial.printf("[mc] UI DM send: %s, %u B\n", sent ? "ok" : "failed",
                  (unsigned)strlen(g_kbText));
    return sent;
  }
  const int chan = chatChannel(g_chatSel);
  if (chan < 0) return false;
  const bool replying = g_replySeq != 0 && g_replyName[0] != 0;
  char wire[om::kMeshTextCap + om::kMeshNameMax + 4];
  if (replying) {
    snprintf(wire, sizeof(wire), "@%s %s", g_replyName, g_kbText);
  } else {
    snprintf(wire, sizeof(wire), "%s", g_kbText);
  }
  const bool sent = om::meshLinkSend(chan, wire);
  if (sent) om::sounds::playEvent(SoundEvent::Sent);
  else om::sounds::playEvent(SoundEvent::Error);
  // EST-399: same rule for the channel send (this one also carries the reply mention).
  Serial.printf("[mc] UI send: %s, %u B%s\n", sent ? "ok" : "failed", (unsigned)strlen(wire),
                replying ? ", reply" : "");
  return sent;
}

// Send the draft through the open chat (channel or DM, a reply or not, from the letters page or the
// emoji page). EST-406: the composer's send button on the draft line is the ONE door; every path
// ends here, so they all clear the same state. It does nothing on an empty or whitespace-only draft
// (chatSend() refuses it), which is the same state the button is drawn dim in.
static void chatSendDraft() {
  if (!chatSend()) return;
  g_kbText[0] = 0;
  g_replySeq = 0;
  g_replyName[0] = 0;
  g_kb.close();   // the next open goes through openSheet() and starts on letters, shift off
}

// One emoji from the keyboard: four UTF-8 bytes at most, refused as a unit when the draft budget
// has no room for it (never a broken sequence). The pick moves to the front of the Recent row.
static void chatEmojiPick(uint32_t cp) {
  char bytes[5] = {0};
  const int n = om::ui::utf8Encode(cp, bytes);
  if (n <= 0) return;
  bytes[n] = 0;
  if (!om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), bytes, chatDraftAllowance())) {
    Serial.printf("[chat] emoji U+%04lX refused: draft budget full\n", (unsigned long)cp);
    return;
  }
  g_emojiRecent.use(cp);
  // EST-399: RAM only. The one NVS write for the Recent row goes out when the emoji page is left, or
  // after 30 s without another pick (emojiPersistStep from the loop). Six emoji used to be six flash
  // commits, and the write's result was never looked at (EST-398 #4).
  g_emojiSave.changed(millis());
  Serial.printf("[chat] emoji U+%04lX -> recent %u (save pending)\n", (unsigned long)cp,
                (unsigned)g_emojiRecent.count);
}

// EST-346: the release of a hold on s, c or z enters the accented letter the bubble showed. One code
// point (two UTF-8 bytes), appended as a whole through the same budget as every other key: a full
// draft refuses it rather than splitting the sequence.
static void chatAccentCommit() {
  if (g_accentCp == 0) return;
  char bytes[5] = {0};
  const int n = om::ui::utf8Encode(g_accentCp, bytes);
  if (n <= 0) return;
  bytes[n] = 0;
  if (!om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), bytes, chatDraftAllowance())) {
    Serial.printf("[chat] accent U+%04lX refused: draft budget full\n", (unsigned long)g_accentCp);
    return;
  }
  Serial.printf("[chat] accent U+%04lX (%s), %u bytes in the draft\n", (unsigned long)g_accentCp,
                bytes, (unsigned)strlen(g_kbText));
}

// The sheet owns the keyboard state; this applies one key and says whether the draft was sent. The
// draft counts bytes against the same budget the counter shows, and a key that would pass it does
// nothing at all (Filip, 2026-11-10: no silent cut on send).
static void chatKey(const om::ui::ChatHitResult& hit) {
  const int allow = chatDraftAllowance();
  switch (hit.keyKind) {
    case om::ui::KeyKind::Shift:
      g_kb.toggleShift();
      break;
    case om::ui::KeyKind::Mode:
      g_kb.toggleNumbers();
      break;
    case om::ui::KeyKind::Emoji:
      g_kb.toggleEmoji();
      g_emojiScroll = 0;
      break;
    case om::ui::KeyKind::Space:
      om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), " ", allow);
      break;
    case om::ui::KeyKind::Del:
      om::ui::composeBackspace(g_kbText);   // one whole code point, never half an emoji
      break;
    case om::ui::KeyKind::Send:
      chatSendDraft();
      break;
    case om::ui::KeyKind::Reveal:
      break;   // a chat draft has no secret to reveal
    case om::ui::KeyKind::Char: {
      char one[2] = {hit.keyCh, 0};
      if (g_kb.shift && !g_kb.nums() && one[0] >= 'a' && one[0] <= 'z') one[0] = (char)(one[0] - 32);
      om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), one, allow);
      break;
    }
  }
}

static void showTab(int tab);
static void drawSettings();   // the Chat header's gear opens it (defined below)

// Open (or create) a DM thread for a contact and show it in the chat screen. This is what the
// message sheet's "Direct message" row and a tap on a sender's name both call (EST-342).
static bool chatOpenDmFor(const char* name) {
  int thread = -1;
  if (!om::meshDmOpenByName(name, &thread)) {
    // EST-399: no name (rule 9: it is the contact the user typed or tapped).
    Serial.printf("[chat] DM refused: unknown contact\n");
    return false;
  }
  refreshChats();
  for (int i = g_channelCount; i < g_chatCount; ++i) {
    if (g_chats[i].dm && g_chats[i].thread == thread) {
      chatSelectChat(i);
      // EST-355: Nodes -> Chat is a full screen change like any tab switch (both pages are dark, so
      // the dip rule keeps it instant, but it goes through the one path and logs its line).
      if (g_tab != 1) showTab(1);
      else drawChat();
      return true;
    }
  }
  return false;
}

// One row of the message sheet. The rows were built from what can work (message_sheet.h), so a row
// that is here does something; the informational ones (Path, Heard repeats) just close the sheet.
static void handleSheetAction(const om::ui::ChatHitResult& hit) {
  if (hit.index < 0 || hit.index >= g_chatMsgCount) {
    g_bubMenuSeq = 0;
    return;
  }
  const om::ui::ChatMsgView& m = g_chatMsgs[hit.index];
  switch (hit.sheet) {
    case om::ui::SheetAction::Reply:
      g_replySeq = hit.seq;
      // Copy the name now: the ring may shift before Send, and the reply must still address the
      // sender the user tapped, even if this message is the one that gets dropped.
      snprintf(g_replyName, sizeof(g_replyName), "%s", m.name);
      g_bubMenuSeq = 0;
      g_kbText[0] = 0;
      g_kb.openSheet();
      // EST-399: the sequence number being answered, not the sender's name (rule 9).
      Serial.printf("[chat] reply opened: seq %lu\n", (unsigned long)g_replySeq);
      break;
    case om::ui::SheetAction::CopyText:
      // COPY takes the whole text, cut only by the composer's own byte budget: on a code point
      // boundary and with an ellipsis when it has to shorten (composeCopy).
      om::ui::composeCopy(g_kbText, (int)sizeof(g_kbText), m.text, chatDraftAllowance());
      g_replySeq = 0;
      g_replyName[0] = 0;
      g_bubMenuSeq = 0;
      g_kb.openSheet();
      Serial.println("[chat] copied a message into the draft");
      break;
    case om::ui::SheetAction::Mention: {
      // "@Name " in the draft without the reply bar: a plain message that starts with a mention.
      char tag[om::kMeshNameCap + 3];
      snprintf(tag, sizeof(tag), "@%s ", m.name);
      om::ui::composeAppend(g_kbText, (int)sizeof(g_kbText), tag, chatDraftAllowance());
      g_replySeq = 0;
      g_replyName[0] = 0;
      g_bubMenuSeq = 0;
      g_kb.openSheet();
      // EST-399: that a mention went in, not the name it names (rule 9).
      Serial.printf("[chat] mention prepended: %u B\n", (unsigned)strlen(tag));
      break;
    }
    case om::ui::SheetAction::NodeDetails: {
      om::nodes_tab::selectByName(m.name);
      g_bubMenuSeq = 0;
      g_selector = false;
      showTab(0);
      return;
    }
    case om::ui::SheetAction::ShowOnMap: {
      om::MeshContact c{};
      if (om::meshContactByName(m.name, &c) && c.has_pos) {
        const double lat = (double)c.lat_e6 / 1e6;
        const double lon = (double)c.lon_e6 / 1e6;
        g_bubMenuSeq = 0;
        om::map_tab::showPoint(lat, lon, m.name);
        // EST-397: the name only. The contact's exact point is rule 9's first "no", and this line put
        // it in the log on every map open from a chat.
        Serial.printf("[chat] map: opening the node's position\n");
        showTab(2);
        return;
      }
      g_bubMenuSeq = 0;
      break;
    }
    case om::ui::SheetAction::Resend: {
      // The same text as a NEW packet: a channel send, or a fresh DM through the companion's path.
      const int thread = chatThread(g_chatSel);
      const int chan = chatChannel(g_chatSel);
      if (thread >= 0) {
        const bool sent = om::meshDmSend(thread, m.text);
        // EST-399: the verdict and the length, never the body (rule 9; EST-396 #2).
        Serial.printf("[chat] DM resend %s, %u B\n", sent ? "ok" : "failed",
                      (unsigned)strlen(m.text));
      } else if (chan >= 0) {
        const bool sent = om::meshLinkSend(chan, m.text);
        Serial.printf("[chat] resend %s, %u B\n", sent ? "ok" : "failed",
                      (unsigned)strlen(m.text));
      }
      g_bubMenuSeq = 0;
      break;
    }
    case om::ui::SheetAction::DirectMessage: {
      // EST-342: the row exists only for a known contact with a key, and the thread opens (or is
      // created empty) here.
      g_bubMenuSeq = 0;
      chatOpenDmFor(m.name);
      return;
    }
    case om::ui::SheetAction::Path:            // informational, shown in the row's value
    case om::ui::SheetAction::HeardRepeats:    // informational, shown in the row's value
    case om::ui::SheetAction::None:
    default:
      g_bubMenuSeq = 0;
      break;
  }
}

// EST-382: one advert, from the button or (via the USB command) the same facade call. The 30 s guard
// per kind lives in mesh_link, so the key and `advert local|flood` can never disagree. `r` is 0 when
// sent, a positive number of seconds still to wait, and negative when the radio refused.
static void showToast(const char* text);

static void chatAdvertSend(bool flood) {
  g_advertMenu = false;   // a tap on an option sends and closes
  const int r = om::meshSendAdvert(flood);
  char msg[48];
  if (r == 0) {
    snprintf(msg, sizeof(msg), "%s", flood ? "Advert sent (flood)" : "Advert sent (nearby)");
  } else if (r > 0) {
    snprintf(msg, sizeof(msg), "Advert already sent, wait %ds", r);
  } else {
    snprintf(msg, sizeof(msg), "Advert not sent");
  }
  showToast(msg);
}

// One tap on the Chat tab. The screen says what was hit with the same rectangles it drew.
static void handleChatTap(int x, int y) {
  const om::ui::Layout& L = om::ui::l2();
  om::ui::ChatView v;
  buildChatView(v);
  const om::ui::ChatHitResult hit = om::ui::chatScreenHit(v, x, y);
  switch (hit.hit) {
    case om::ui::ChatHit::Head:
      // The header is the selector's own door: it opens the dropdown and closes it again. EST-382:
      // the two dropdowns are exclusive, so opening the selector closes the ADVERT menu.
      g_selector = !g_selector;
      g_advertMenu = false;
      g_kb.close();
      g_bubMenuSeq = 0;
      if (g_selector) g_selScroll = 0;
      break;
    case om::ui::ChatHit::Advert:
      // The key toggles its own small dropdown; the chat selector is the other one and must close.
      g_advertMenu = !g_advertMenu;
      g_selector = false;
      g_kb.close();
      g_bubMenuSeq = 0;
      break;
    case om::ui::ChatHit::AdvertFlood:
      chatAdvertSend(true);
      break;
    case om::ui::ChatHit::AdvertLocal:
      chatAdvertSend(false);
      break;
    case om::ui::ChatHit::AdvertClose:
      g_advertMenu = false;   // a tap on the panel but not an option: close only, never act behind
      break;
    case om::ui::ChatHit::SelRow:
      chatSelectChat(hit.index);
      break;
    case om::ui::ChatHit::SelManage:
      g_selector = false;
      openChannelList();
      return;
    case om::ui::ChatHit::SelClose:
      g_selector = false;
      break;
    case om::ui::ChatHit::Msg:
      g_bubMenuSeq = hit.seq;   // hold the message id, not its position in the ring
      g_kb.close();             // the sheet needs the room and covers the keyboard anyway
      break;
    case om::ui::ChatHit::SenderName: {
      // EST-342: a tap on the sender's name is the sheet's "Direct message" row.
      if (hit.index >= 0 && hit.index < g_chatMsgCount && !g_chatMsgs[hit.index].mine) {
        chatOpenDmFor(g_chatMsgs[hit.index].name);
        return;
      }
      g_bubMenuSeq = hit.seq;
      g_kb.close();
      break;
    }
    case om::ui::ChatHit::SheetRow:
      handleSheetAction(hit);
      break;
    case om::ui::ChatHit::SheetClose:
      g_bubMenuSeq = 0;
      break;
    case om::ui::ChatHit::Field:
      g_kb.openSheet();   // always on the letters page, shift off (EST-346)
      break;
    case om::ui::ChatHit::Key:
      chatKey(hit);
      break;
    case om::ui::ChatHit::EmojiCell:
      chatEmojiPick(hit.emojiCp);
      break;
    case om::ui::ChatHit::EmojiCat:
      if (hit.emojiGroup >= 0 && hit.emojiGroup < om::ui::kEmojiGroupCount) {
        g_emojiGroup = hit.emojiGroup;
        g_emojiScroll = 0;
      }
      break;
    case om::ui::ChatHit::EmojiBack:
      g_kb.showLetters();   // back to the letters/numbers keyboard page
      g_emojiScroll = 0;
      break;
    // EST-406: the one Send door for channel, DM, reply and the emoji page. The button is on the
    // draft line and is drawn dim while the draft is empty or only whitespace; chatSendDraft() then
    // does nothing, exactly like the dim look says.
    case om::ui::ChatHit::SendDraft:
      chatSendDraft();
      break;
    case om::ui::ChatHit::Outside:
      // Belt and braces: the shell already closed the sheet on the PRESS that landed above it and
      // spent that gesture (EST-339), so this is only reached if a hit test runs on an open sheet.
      g_kb.close();
      break;
    case om::ui::ChatHit::None:
      // Not the chat surface: the tab bar (hidden while the sheet is open), the fault mark and the
      // status gear.
      if (!g_kb.open) {
        const int tab = L.tabAt(x, y);
        if (tab >= 0) { showTab(tab); return; }
      }
      // A tap on the radio fault mark says which fault it is; nothing when the mark is not showing.
      if (L.radioFault().contains(x, y)) {
        showRadioFaultToast();
        return;
      }
      // The gear is the only door to Settings (Filip, 2026-11-10); the channel list is reached from
      // the selector's "Manage channels" row.
      if (L.gear().contains(x, y)) {
        openSettings(1, om::ui::SettingsTab::Chat);
        return;
      }
      return;
  }
  drawChat();
}

