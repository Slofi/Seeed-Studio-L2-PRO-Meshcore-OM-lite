  *m = om::ui::NodeInfoModel();
  snprintf(m->name, sizeof(m->name), "%s", c.name);
  m->advType = c.type;
  m->hasKey = c.has_key;
  if (c.has_key) memcpy(m->key, c.pub_key, sizeof(m->key));
