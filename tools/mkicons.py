#!/usr/bin/env python3
"""Render the OM Lite icon masks and the C++ table the widgets blend over the frame.

The old cog was drawn with circles and rectangles and never matched the mock's U+2699 glyph. The mock
uses the font glyph, so the gear here is Pillow's rendering of U+2699 from DejaVu Sans, supersampled
4x and reduced to an 8-bit alpha mask at the exact on-screen size. Wi-Fi and Bluetooth are simple
vector shapes (three arcs plus a dot; the rune), rendered the same way for the later tabs.

Usage:
  tools/mkicons.py                 # writes src/ui/icons.cpp/.h and docs/shots/icons-preview.png
  tools/mkicons.py --out-dir /tmp/x --preview /tmp/icons.png

Every pixel is 0..255 coverage; widgets/drawIcon() blends the requested colour over the background
with it. The preview is a contact sheet: each icon at 1:1 and at 8x (nearest neighbour), so the glyph
can be judged before flashing.
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
SUPERSAMPLE = 4

# name, kind, screen size. The gear keeps the current 9 px slot; the two future tab icons use the
# 11 px tab icon slot.
ICONS = [
    ("Gear", "glyph", 0x2699, 9),
    ("Wifi", "wifi", None, 11),
    ("Bluetooth", "bluetooth", None, 11),
]


def fit(img, size):
    """Scale an L canvas to fit `size`, preserving aspect, and centre it on a size x size canvas."""
    w, h = img.size
    if w <= 0 or h <= 0:
        return Image.new("L", (size, size), 0)
    if w >= h:
        nw, nh = size, max(1, int(round(h * size / w)))
    else:
        nh, nw = size, max(1, int(round(w * size / h)))
    small = img.resize((nw, nh), Image.LANCZOS)
    canvas = Image.new("L", (size, size), 0)
    canvas.paste(small, ((size - nw) // 2, (size - nh) // 2))
    return canvas


def glyph_mask(code, size):
    work = size * SUPERSAMPLE
    font = ImageFont.truetype(FONT, work)
    ch = chr(code)
    bbox = font.getbbox(ch)
    if bbox is None:
        raise SystemExit("font has no glyph U+%04X" % code)
    x0, y0, x1, y1 = bbox
    w, h = max(1, x1 - x0), max(1, y1 - y0)
    canvas = Image.new("L", (w, h), 0)
    ImageDraw.Draw(canvas).text((-x0, -y0), ch, font=font, fill=255)
    return fit(canvas, size)


def wifi_mask(size):
    work = size * SUPERSAMPLE
    canvas = Image.new("L", (work, work), 0)
    d = ImageDraw.Draw(canvas)
    cx = work // 2
    base = int(work * 0.88)
    dot_r = max(1, int(round(work * 0.055)))
    stroke = max(1, int(round(work * 0.065)))
    d.ellipse((cx - dot_r, base - dot_r, cx + dot_r, base + dot_r), fill=255)
    for frac in (0.28, 0.49, 0.70):
        r = int(round(work * frac))
        d.arc((cx - r, base - r, cx + r, base + r), start=225, end=315, fill=255, width=stroke)
    return fit(canvas, size)


def bluetooth_mask(size):
    work = size * SUPERSAMPLE
    canvas = Image.new("L", (work, work), 0)
    d = ImageDraw.Draw(canvas)
    cx = work // 2
    y0 = int(work * 0.12)
    y1 = work - y0
    mid = (y0 + y1) // 2
    dx = int(round(work * 0.23))
    stroke = max(1, int(round(work * 0.07)))
    pts_a = (cx, y0)
    pts_b = (cx + dx, mid)
    pts_c = (cx - dx, mid)
    pts_d = (cx, y1)
    for a, b in ((pts_a, pts_b), (pts_b, pts_d), (pts_a, pts_c), (pts_c, pts_d), (pts_a, pts_d)):
        d.line((a, b), fill=255, width=stroke, joint="curve")
    return fit(canvas, size)


def clean(mask):
    """Drop the faint LANCZOS dust and stretch the remaining coverage to full 0..255."""
    px = mask.load()
    w, h = mask.size
    raw_peak = 0
    for y in range(h):
        for x in range(w):
            if px[x, y] > raw_peak:
                raw_peak = px[x, y]
    if raw_peak <= 8:
        return mask, 0
    scale = 255.0 / (raw_peak - 8)
    for y in range(h):
        for x in range(w):
            a = px[x, y]
            px[x, y] = 0 if a < 8 else min(255, int(round((a - 8) * scale)))
    return mask, 255


def c_array(name, mask):
    w, h = mask.size
    data = mask.tobytes()
    lines = ["const uint8_t %s[] PROGMEM = {" % name]
    for y in range(h):
        row = data[y * w:(y + 1) * w]
        lines.append("  " + ", ".join("0x%02x" % b for b in row) + ",")
    lines.append("};")
    return "\n".join(lines)


def write_cpp(icons, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    h_lines = [
        "// Generated by tools/mkicons.py - do not edit by hand.",
        "// 8-bit alpha masks; widgets draw them by blending a colour over the background.",
        "// SPDX-License-Identifier: MIT (generated data; the gear is DejaVu Sans, Bitstream Vera licence).",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace om {",
        "namespace ui {",
        "",
        "struct IconMask {",
        "  uint8_t w;",
        "  uint8_t h;",
        "  const uint8_t* alpha;",
        "};",
        "",
    ]
    c_lines = [
        "// Generated by tools/mkicons.py - do not edit by hand.",
        '#include "ui/icons.h"',
        "",
        "#include <Arduino.h>",
        "",
        "namespace om {",
        "namespace ui {",
        "",
    ]
    for name, kind, _code, size in icons:
        ident = "k" + name + "Mask"
        h_lines.append("extern const IconMask kIcon%s;" % name)
        c_lines.append(c_array(ident, kind[1]))
        c_lines.append("const IconMask kIcon%s PROGMEM = {%d, %d, %s};" % (name, size, size, ident))
        c_lines.append("")
    h_lines += ["}  // namespace ui", "}  // namespace om", ""]
    c_lines += ["}  // namespace ui", "}  // namespace om", ""]
    with open(os.path.join(out_dir, "icons.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(h_lines))
    with open(os.path.join(out_dir, "icons.cpp"), "w", encoding="utf-8") as f:
        f.write("\n".join(c_lines))


def write_preview(icons, path):
    bg = (0x17, 0x16, 0x14)
    fg = (0x93, 0xa0, 0xb4)
    ink = (0xe8, 0xed, 0xf5)
    zoom = 8
    label_font = ImageFont.truetype(FONT, 12)
    margin = 12
    row_h = 8 * 11 + 34
    width = 460
    height = margin * 2 + row_h * len(icons)
    sheet = Image.new("RGB", (width, height), bg)
    d = ImageDraw.Draw(sheet)
    y = margin
    for name, kind, _code, size in icons:
        mask = kind[1]
        d.text((margin, y), "%s  %dx%d" % (name, size, size), font=label_font, fill=ink)
        d.text((margin, y + 18), "1:1", font=label_font, fill=fg)
        one = Image.new("RGB", (size, size), bg)
        one_px = one.load()
        mpx = mask.load()
        for yy in range(size):
            for xx in range(size):
                a = mpx[xx, yy]
                if a:
                    one_px[xx, yy] = tuple(
                        (fg[i] * a + bg[i] * (255 - a)) // 255 for i in range(3))
        sheet.paste(one, (margin + 44, y + 12))
        d.text((margin + 84, y + 18), "8x", font=label_font, fill=fg)
        big = mask.resize((size * zoom, size * zoom), Image.NEAREST)
        big_rgb = Image.new("RGB", big.size, bg)
        bpx = big_rgb.load()
        bmpx = big.load()
        for yy in range(big.size[1]):
            for xx in range(big.size[0]):
                a = bmpx[xx, yy]
                if a:
                    bpx[xx, yy] = tuple(
                        (fg[i] * a + bg[i] * (255 - a)) // 255 for i in range(3))
        sheet.paste(big_rgb, (margin + 118, y + 6))
        y += row_h
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    sheet.save(path)
    print("preview %s" % path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default=os.path.join(os.path.dirname(__file__), "..", "src", "ui"))
    ap.add_argument("--preview", default=os.path.join(
        os.path.dirname(__file__), "..", "docs", "shots", "icons-preview.png"))
    args = ap.parse_args()

    icons = []
    for name, kind, code, size in ICONS:
        if kind == "glyph":
            mask = glyph_mask(code, size)
        elif kind == "wifi":
            mask = wifi_mask(size)
        elif kind == "bluetooth":
            mask = bluetooth_mask(size)
        else:
            raise SystemExit("unknown icon kind %s" % kind)
        mask, peak = clean(mask)
        nonzero = sum(1 for b in mask.tobytes() if b)
        print("%-9s %2dx%-2d  %3d nonzero, peak %d" % (name, size, size, nonzero, peak))
        icons.append((name, (kind, mask), code, size))

    write_cpp(icons, os.path.abspath(args.out_dir))
    write_preview(icons, os.path.abspath(args.preview))


if __name__ == "__main__":
    main()
