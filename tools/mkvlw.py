#!/usr/bin/env python3
"""Generate an anti-aliased VLW font as a PROGMEM C array for OM Lite.

Why: the old src/font_om12.cpp / font_om18.cpp are 1-bit GFXfonts (mkfont.py thresholds at 128),
so they cannot be smooth. LovyanGFX draws VLW fonts through draw_alpha_bitmap_common(), which blends
an 8-bit coverage value between the foreground and the background colour. That is the smooth path.

The VLW layout is the one LovyanGFX's VLWfont::loadFont()/drawChar() expects (big-endian):
  24-byte header: glyph count, encoder version, yAdvance, (unused), ascent, descent
  per glyph 28 bytes: unicode, height, width, xAdvance, dY (top above baseline), dX, padding
  then the glyph bitmaps, 8-bit coverage, width * height bytes, in the same order, no padding.

Usage:
  tools/mkvlw.py --size 11 --name Sans11 --font /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf \
                 --out src/ui/font_sans11.cpp [--extra 0x2699,0xb7] [--preview /tmp/sans11.png]

The name becomes the C identifier (kSans11Data / kSans11DataLen), so it must match ui/fonts.h.

--extra adds code points outside ASCII (comma separated, decimal or 0x hex). The records are written
in ascending code point order, which is what LovyanGFX's binary search (std::lower_bound) needs.
"""
import argparse
import struct

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7E


def code_points(extra):
    codes = set(range(FIRST, LAST + 1))
    for tok in extra.split(","):
        tok = tok.strip()
        if tok:
            codes.add(int(tok, 0))
    return sorted(codes)


def describe(extra):
    extras = [c for c in code_points(extra) if not (FIRST <= c <= LAST)]
    if not extras:
        return "ASCII 0x20-0x7E"
    return "ASCII 0x20-0x7E plus " + ", ".join("U+%04X" % c for c in extras)


def render(ttf, size, codes):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in codes:
        ch = chr(code)
        advance = max(1, int(round(font.getlength(ch))))
        bbox = font.getbbox(ch)
        if bbox is None:
            glyphs.append((code, 0, 0, advance, 0, 0, b""))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:                 # space and friends: advance only
            glyphs.append((code, 0, 0, advance, 0, 0, b""))
            continue
        if w > 255 or h > 255:
            raise SystemExit("glyph 0x%02x does not fit the VLW byte fields" % code)
        # Render on a canvas whose top-left is the glyph origin. PIL's bbox is relative to that
        # origin (y=0 at the ascender line), so the crop is exact.
        canvas = Image.new("L", (w, h), 0)
        ImageDraw.Draw(canvas).text((-x0, -y0), ch, font=font, fill=255)
        d_y = ascent - y0                    # glyph top, positive above the baseline
        d_x = x0                             # left bearing
        glyphs.append((code, h, w, advance, d_y, d_x, canvas.tobytes()))
    return glyphs, ascent, descent


def emit(glyphs, ascent, descent, y_advance, out_path, ttf, size, name, range_desc):
    head = struct.pack(">IIIIII", len(glyphs), 3, y_advance, 0, ascent, descent)
    records = bytearray()
    bitmaps = bytearray()
    for (code, h, w, adv, dy, dx, pix) in glyphs:
        records += struct.pack(">IIIIiiI", code, h, w, adv, dy, dx, 0)
        bitmaps += pix
    blob = head + bytes(records) + bytes(bitmaps)

    lines = [
        "// Generated by tools/mkvlw.py - do not edit by hand.",
        "// Face: %s at %d px, %s, 8-bit anti-aliased coverage (VLW)." % (
            ttf.rsplit("/", 1)[-1], size, range_desc),
        "// SPDX-License-Identifier: MIT (generated data; the face is DejaVu, Bitstream Vera licence).",
        '#include "ui/fonts.h"',
        "",
        "namespace om {",
        "namespace ui {",
        "",
        "const uint8_t k%sData[] PROGMEM = {" % name,
    ]
    for i in range(0, len(blob), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in blob[i:i + 16]) + ",")
    lines += [
        "};",
        "const uint32_t k%sDataLen = sizeof(k%sData);" % (name, name),
        "",
        "}  // namespace ui",
        "}  // namespace om",
        "",
    ]
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))
    return len(blob)


def preview(glyphs, ascent, size, out_path, sample, scale=3):
    by_code = {g[0]: g for g in glyphs}
    pad = 4
    w, h = 320, 120
    img = Image.new("RGB", (w, h), (0x13, 0x12, 0x10))
    d = ImageDraw.Draw(img)
    pen = pad
    line = 0
    for ch in sample:
        if ch == "\n":
            pen = pad
            line += 1
            continue
        g = by_code.get(ord(ch))
        if g is None or g[2] == 0:
            pen += 5
            continue
        _, gh, gw, adv, dy, dx, pix = g
        top = pad + line * (size + 4) + (ascent - dy)
        for y in range(gh):
            for x in range(gw):
                a = pix[y * gw + x]
                if a:
                    px, py = pen + dx + x, top + y
                    if 0 <= px < w and 0 <= py < h:
                        # blend like LovyanGFX does, so the preview shows the anti-aliasing
                        c = tuple((0x13 + (fg - 0x13) * a // 255) for fg in (0xE8, 0xB0, 0x4F))
                        d.point((px, py), fill=c)
        pen += adv
        if pen > w - 8:
            pen = pad
            line += 1
    img.resize((w * scale, h * scale), Image.NEAREST).save(out_path)
    return out_path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    ap.add_argument("--size", type=int, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--extra", default="")
    ap.add_argument("--preview", default="")
    ap.add_argument("--sample", default="Nodes  Chat  Map  RPTR\nSLO-RPTR-1  direct  2m")
    a = ap.parse_args()

    codes = code_points(a.extra)
    glyphs, ascent, descent = render(a.font, a.size, codes)
    n = emit(glyphs, ascent, descent, ascent + descent, a.out, a.font, a.size, a.name,
             describe(a.extra))
    print("%s: %d bytes (%d glyphs, ascent %d descent %d)" % (a.out, n, len(glyphs), ascent, descent))
    if a.preview:
        print(preview(glyphs, ascent, a.size, a.preview, a.sample))


if __name__ == "__main__":
    main()
