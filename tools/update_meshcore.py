"""Update the vendored MeshCore core + companion code and write the sha256 manifest.

Usage (Claude runs this; the sandbox has no network):

    tools/update_meshcore.py companion-v1.19.0
    tools/update_meshcore.py companion-v1.19.0 --repo /path/to/MeshCore --dry-run
    tools/update_meshcore.py companion-v1.18.0 --manifest-only --commit 81dbae5

What it does for a real run:
  * clones/fetches the tag (or uses --repo as a local clone),
  * replaces lib/meshcore with the tag's src/ (keeping the local library.json),
  * replaces lib/meshcore_companion's five upstream files from examples/companion_radio,
  * replaces reference/meshcore-companion-<tag>/ with examples/companion_radio,
  * writes lib/MESHCORE_VERSION with the tag, commit and a sha256 manifest,
  * prints the upstream diff of examples/companion_radio between the old and new tag,
  * never writes src/ (the board glue and facade are ours; the printed diff is what to check).

--dry-run writes nothing and works offline against a local clone path.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DEFAULT_REPO = "https://github.com/meshcore-dev/MeshCore.git"
COMPANION_FILES = [
    "MyMesh.cpp",
    "MyMesh.h",
    "DataStore.cpp",
    "DataStore.h",
    "NodePrefs.h",
    "AbstractUITask.h",
]
MANIFEST = "lib/MESHCORE_VERSION"
CORE_DIR = "lib/meshcore"
COMPANION_DIR = "lib/meshcore_companion"
REFERENCE_PREFIX = "reference/meshcore-companion-"


def run_git(repo: str, *args: str, check: bool = True) -> str:
    cmd = ["git", "-C", repo] + list(args)
    res = subprocess.run(cmd, capture_output=True, text=True)
    if check and res.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} failed: {res.stderr.strip()}")
    return res.stdout.strip()


def reference_name(tag: str) -> str:
    """reference/meshcore-companion-v1.18.0 from tag companion-v1.18.0."""
    base = tag[len("companion-"):] if tag.startswith("companion-") else tag
    return f"{REFERENCE_PREFIX}{base}"


def read_current_tag(root: Path) -> tuple[str | None, str | None]:
    path = root / MANIFEST
    if not path.exists():
        return None, None
    tag = commit = None
    for line in path.read_text().splitlines():
        if line.startswith("tag "):
            tag = line[4:].strip()
        elif line.startswith("commit "):
            commit = line[7:].strip()
    return tag, commit


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 256), b""):
            h.update(chunk)
    return h.hexdigest()


def files_under(root: Path, rel_dir: str) -> list[Path]:
    d = root / rel_dir
    if not d.exists():
        return []
    out = []
    for p in sorted(d.rglob("*")):
        if p.is_file():
            out.append(p.relative_to(root))
    return out


def write_manifest(root: Path, tag: str, commit: str, reference_dir: str) -> None:
    lines = [
        "# MeshCore vendor manifest. Generated by tools/update_meshcore.py; do not hand edit.",
        "# test/host/test_meshcore_manifest.py fails if a file here is edited, added or removed.",
        f"tag {tag}",
        f"commit {commit}",
    ]
    sections = [CORE_DIR, COMPANION_DIR, reference_dir]
    for section in sections:
        lines.append(f"section {section}")
        for rel in files_under(root, section):
            lines.append(f"{sha256_file(root / rel)}  {rel.as_posix()}")
    (root / MANIFEST).write_text("\n".join(lines) + "\n")
    print(f"wrote {MANIFEST}: tag {tag}, commit {commit}, {len(sections)} sections")


def copy_tree(src: Path, dst: Path) -> None:
    dst.mkdir(parents=True, exist_ok=True)
    for item in src.iterdir():
        target = dst / item.name
        if item.is_dir():
            shutil.copytree(item, target, dirs_exist_ok=True)
        else:
            shutil.copy2(item, target)


def replace_core(root: Path, upstream_src: Path) -> None:
    core = root / CORE_DIR
    keep = {}
    for name in ("library.json",):
        p = core / name
        if p.exists():
            keep[name] = p.read_bytes()
    if core.exists():
        shutil.rmtree(core)
    copy_tree(upstream_src, core)
    for name, data in keep.items():
        (core / name).write_bytes(data)


def replace_companion(root: Path, upstream_examples: Path) -> None:
    dst = root / COMPANION_DIR
    dst.mkdir(parents=True, exist_ok=True)
    for name in COMPANION_FILES:
        src = upstream_examples / name
        if not src.exists():
            raise RuntimeError(f"upstream companion file missing: {src}")
        shutil.copy2(src, dst / name)
    # Keep our local README, licence and library.json. The five code files above are the vendored set.


def replace_reference(root: Path, upstream_examples: Path, tag: str) -> str:
    rel = reference_name(tag)
    dst = root / rel
    if dst.exists():
        shutil.rmtree(dst)
    copy_tree(upstream_examples, dst)
    # The upstream example does not carry a licence file; keep the MIT notice next to it.
    licence = root / COMPANION_DIR / "LICENSE-MeshCore-MIT.txt"
    if licence.exists():
        shutil.copy2(licence, dst / licence.name)
    (dst / "README.md").write_text(
        f"# Reference only, not built\n\n"
        f"MeshCore `examples/companion_radio` at tag `{tag}`, copied by "
        f"`tools/update_meshcore.py`. Our built copy is `lib/meshcore_companion/`; this folder is "
        f"for reading the protocol and checking the printed diff. MIT licence.\n"
    )
    return rel


def print_companion_diff(repo: str, old_tag: str | None, new_tag: str) -> None:
    if old_tag and old_tag != new_tag:
        res = subprocess.run(
            ["git", "-C", repo, "diff", "--stat", f"{old_tag}..{new_tag}", "--", "examples/companion_radio"],
            capture_output=True,
            text=True,
        )
        if res.returncode == 0 and res.stdout.strip():
            print(f"\n--- examples/companion_radio diff {old_tag}..{new_tag} ---")
            print(res.stdout.rstrip())
            body = subprocess.run(
                ["git", "-C", repo, "diff", f"{old_tag}..{new_tag}", "--", "examples/companion_radio"],
                capture_output=True,
                text=True,
            )
            print(body.stdout.rstrip())
        else:
            print(f"\n(no companion_radio diff available for {old_tag}..{new_tag} in this clone)")
    else:
        print("\n(old tag unknown or unchanged: no companion_radio diff printed)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tag", help="upstream tag, e.g. companion-v1.19.0")
    ap.add_argument("--repo", default=DEFAULT_REPO, help="git URL or local clone path")
    ap.add_argument("--dry-run", action="store_true", help="write nothing; works offline on a local clone")
    ap.add_argument("--manifest-only", action="store_true", help="only rewrite lib/MESHCORE_VERSION")
    ap.add_argument("--commit", default=None, help="commit to record with --manifest-only")
    args = ap.parse_args()

    root = Path(__file__).resolve().parent.parent
    old_tag, old_commit = read_current_tag(root)

    if args.manifest_only:
        commit = args.commit or old_commit or "unknown"
        reference_dir = reference_name(args.tag)
        write_manifest(root, args.tag, commit, reference_dir)
        return 0

    repo_is_local = Path(args.repo).exists()
    tmp = None
    try:
        if repo_is_local:
            repo = str(Path(args.repo).resolve())
        else:
            tmp = tempfile.mkdtemp(prefix="meshcore-")
            repo = tmp
            print(f"cloning {args.repo} ({args.tag}) ...")
            subprocess.run(
                ["git", "clone", "--quiet", "--depth", "1", "--branch", args.tag, args.repo, repo],
                check=True,
            )
            # A shallow clone has only the new tag. Fetch the old one (when known) so the printed
            # companion diff is real, not a "no diff available" note.
            if old_tag and old_tag != args.tag:
                fetch = subprocess.run(
                    ["git", "-C", repo, "fetch", "--quiet", "--depth", "1", "origin", "tag", old_tag],
                    capture_output=True,
                    text=True,
                )
                if fetch.returncode != 0:
                    print(f"(could not fetch the old tag {old_tag}: {fetch.stderr.strip()})")
                    old_tag = None

        commit = run_git(repo, "rev-parse", f"{args.tag}^{{commit}}")
        print(f"tag {args.tag} -> commit {commit}")

        # The tree at the tag, not the working tree.
        if repo_is_local:
            work = Path(tempfile.mkdtemp(prefix="meshcore-tree-"))
            tar = work.parent / (work.name + ".tar")
            subprocess.run(
                ["git", "-C", repo, "archive", "--output", str(tar), args.tag], check=True
            )
            subprocess.run(["tar", "-xf", str(tar), "-C", str(work)], check=True)
            tar.unlink(missing_ok=True)
        else:
            work = Path(repo)

        print_companion_diff(repo, old_tag, args.tag)

        upstream_src = work / "src"
        upstream_examples = work / "examples" / "companion_radio"
        if not upstream_src.is_dir() or not upstream_examples.is_dir():
            raise RuntimeError(f"unexpected upstream layout under {work}")

        if args.dry_run:
            core_count = sum(1 for p in upstream_src.rglob("*") if p.is_file())
            comp_count = sum(1 for p in upstream_examples.rglob("*") if p.is_file())
            print(f"\ndry run: would replace {CORE_DIR} ({core_count} files from src/), "
                  f"{COMPANION_DIR} ({len(COMPANION_FILES)} files), "
                  f"{reference_name(args.tag)}/ ({comp_count} files)")
            print(f"dry run: would write {MANIFEST} (tag {args.tag}, commit {commit})")
            print("dry run: src/ is never touched")
            return 0

        replace_core(root, upstream_src)
        replace_companion(root, upstream_examples)
        reference_dir = replace_reference(root, upstream_examples, args.tag)
        write_manifest(root, args.tag, commit, reference_dir)
        print("done. Next: read the printed diff, adjust src/target.* and src/mesh_link.cpp if "
              "the companion API changed, then build and run test/host/run.sh.")
        return 0
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)
        if repo_is_local and "work" in locals():
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:   # noqa: BLE001 - the tool should print a clear one-line error
        print(f"update_meshcore: {exc}", file=sys.stderr)
        sys.exit(1)
